_COH_FLOOR = 30.0
_ARCH_STYLE = {
    "sae_arditi":                ("#ff7f0e", "o"),  # orange circle
    "txc_base + brickenauxk_a8": ("#1f77b4", "s"),  # blue square
}


def _extract_stage4_points(wang: dict | None) -> list[tuple[float, float, int, float]]:
    """Return (coh, align, feature_id, alpha) tuples from stage-4 cells.

    Drops points where the judge returned None (judge failed at extreme
    α). Coherence floor filtering is applied at plot time, not here, so
    the floor zone is visible in the scatter.
    """
    if wang is None:
        return []
    points: list[tuple[float, float, int, float]] = []
    finalists = (wang.get("stage4") or {}).get("finalists", [])
    if finalists:
        for f in finalists:
            fid = int(f.get("feature_id", -1))
            for r in f.get("rows", []):
                a = r.get("mean_align")
                c = r.get("mean_coh")
                if a is None or c is None:
                    continue
                points.append((float(c), float(a), fid, float(r["alpha"])))
    else:
        # Back-compat: 1.0.0 abbreviated frontier (flat list).
        for r in wang.get("frontier", []):
            a = r.get("mean_align")
            c = r.get("mean_coh")
            if a is None or c is None:
                continue
            points.append((float(c), float(a),
                           int(r.get("feature_id", -1)), float(r["alpha"])))
    return points


def _pareto_upper_right(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    """Upper-right Pareto frontier: a point survives iff no other has
    both coh ≥ this AND align ≥ this. Returns frontier in ascending coh."""
    if not points:
        return []
    # Sort by coh desc, then iterate keeping running max align.
    pts = sorted(points, reverse=True)
    frontier: list[tuple[float, float]] = []
    running_max_align = -float("inf")
    for x, y in pts:
        if y > running_max_align:
            frontier.append((x, y))
            running_max_align = y
    return sorted(frontier)  # ascending coh for plotting


def _filter_main_cluster(
    points: list[tuple[float, float, int, float]],
) -> list[tuple[float, float, int, float]]:
    """Per-arch outlier filter: drop the bottom 33% by combined score.

    Score = coh + align. The lowest-scoring third is the long dud-α
    tail (low coh and/or low align). Keeping the top two-thirds focuses
    the visualization on the main steering cluster while preserving
    every legitimate top-align cell (the global peak by definition
    survives). The Pareto frontier and the global peak are re-computed
    on the filtered points.
    """
    if len(points) < 4:
        return list(points)
    scored = sorted(points, key=lambda p: -(p[0] + p[1]))  # descending
    keep_n = max(4, int(round(len(scored) * 2 / 3)))
    return scored[:keep_n]


def _save_pareto_scatter(sae_wangs: list[dict], txc_wangs: list[dict], *,
                         dst: Path, organism_label: str,
                         filter_outliers: bool = False) -> Path | None:
    """Coherence × alignment Pareto scatter (paper-grade headline figure).

    Each point is one stage-4 cell — (feature, α, seed) — across both
    paired seeds. Two arches overlaid in one panel; upper-right Pareto
    frontier is drawn as a step line per arch; the global peak per arch
    is highlighted as a star. Coherence floor zone (coh < 30) is shaded.

    Replaces the prior α-vs-align frontier line plot, which was cluttered
    (3 features × 27 α × 2 panels = 162 points per organism on overlapping
    log axes). This view drops α as an axis (it is a steering parameter,
    not a paper-meaningful axis) and surfaces the trade-off directly:
    at any given coherence level, which arch achieves higher alignment-
    injection?

    ``filter_outliers=True`` applies a per-arch Tukey lower-fence filter
    (see ``_filter_main_cluster``) to focus on the main steering cluster,
    dropping the dud-α tail. The Pareto frontier and global peak are
    re-computed on the filtered points for consistency. Title carries
    a "(main cluster)" suffix.
    """
    if not sae_wangs and not txc_wangs:
        return None
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        return None

    sae_pts = [p for w in sae_wangs for p in _extract_stage4_points(w)]
    txc_pts = [p for w in txc_wangs for p in _extract_stage4_points(w)]
    if filter_outliers:
        sae_pts = _filter_main_cluster(sae_pts)
        txc_pts = _filter_main_cluster(txc_pts)

    fig, ax = plt.subplots(figsize=(7.0, 5.5), dpi=140)

    # Shade the incoherent zone (coh < floor) — context, not data.
    ax.axvspan(0, _COH_FLOOR, alpha=0.10, color="gray", zorder=0)

    legend_handles = []
    for arch_label, points in (("sae_arditi", sae_pts),
                                ("txc_base + brickenauxk_a8", txc_pts)):
        if not points:
            continue
        color, marker = _ARCH_STYLE[arch_label]
        coh_align = [(p[0], p[1]) for p in points]
        xs = [p[0] for p in coh_align]
        ys = [p[1] for p in coh_align]
        ax.scatter(xs, ys, color=color, marker=marker, s=24, alpha=0.40,
                   edgecolors="none", zorder=2,
                   label=f"{arch_label} (n={len(coh_align)})")

        # Pareto frontier (upper-right) above coh floor only.
        eligible = [(c, a) for c, a in coh_align if c >= _COH_FLOOR]
        front = _pareto_upper_right(eligible)
        if front:
            fx = [p[0] for p in front]
            fy = [p[1] for p in front]
            ax.step(fx, fy, where="post", color=color, linewidth=2.4,
                    alpha=0.95, zorder=3)

        # Global peak (highest align with coh ≥ floor) as star.
        peak = max(eligible, key=lambda p: p[1], default=None)
        if peak:
            ax.scatter([peak[0]], [peak[1]], color=color, marker="*",
                       s=320, edgecolors="black", linewidth=1.2, zorder=5)
            # Annotation offset based on arch (avoid overlap if peaks near).
            dx = 1.5
            dy = 1.5 if arch_label.startswith("txc") else -3.0
            ax.annotate(
                f"peak {peak[1]:.1f}\n(coh {peak[0]:.1f})",
                xy=peak, xytext=(peak[0] + dx, peak[1] + dy),
                fontsize=9, color=color, weight="bold",
                bbox=dict(boxstyle="round,pad=0.25",
                          facecolor="white", edgecolor=color,
                          linewidth=0.8, alpha=0.92),
                zorder=6,
            )

    # Manually annotate the floor zone.
    y_top = ax.get_ylim()[1]
    ax.text(_COH_FLOOR / 2, y_top * 0.96 if y_top > 0 else 95,
            "incoherent\noutput",
            ha="center", va="top", fontsize=9, color="gray",
            style="italic", zorder=1)

    ax.set_xlabel("Coherence score (Claude Haiku judge, 0–100)", fontsize=11)
    ax.set_ylabel("Alignment-injection score (0–100; higher = more misaligned)",
                  fontsize=11)
    title_suffix = " (main cluster)" if filter_outliers else ""
    ax.set_title(
        f"C6 — coherence × alignment Pareto on {organism_label}{title_suffix}\n"
        f"Each point: one (feature, α, seed) stage-4 cell. "
        f"★ = best align with coh ≥ {_COH_FLOOR:.0f}.",
        fontsize=11.5,
    )
    ax.legend(loc="lower left", fontsize=9, framealpha=0.92)
    ax.grid(True, alpha=0.30, linestyle="-", linewidth=0.5)
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 100)
    ax.tick_params(axis="both", labelsize=10)

    fig.tight_layout()

    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(dst, dpi=300, bbox_inches="tight")
    thumb = dst.with_suffix(".thumb.png")
    fig.savefig(thumb, dpi=48, bbox_inches="tight")
    try:
        from PIL import Image
        with Image.open(thumb) as im:
            w, h = im.size
            if w > 288:
                im.resize((288, int(h * 288 / w))).save(thumb)
    except ImportError:
        pass
    plt.close(fig)
    return dst


def _decision(gap: float) -> str:
    """Map a signed gap (SAE − TXC) to the c6.md decision-tree band.

    Bands are on |gap|. A negative gap means TXC > SAE; the band is the
    same as the absolute value implies — e.g. gap=-3.2 is "Tied" with
    TXC narrowly winning, NOT "Honest negative".
    """
    a = abs(gap)
    direction = "TXC narrowly wins" if gap < 0 else "TXC closes the gap to"
    if a <= 3.0:
        return (f"**Tied** — {direction} within judge σ ≈ 6 align "
                f"(|gap|={a:.2f} ≤ 3) (headline win).")
    if a <= 9.0:
        if gap < 0:
            return ("**Mixed** — TXC strictly beats SAE-arditi (|gap| in "
                    "3–9 align band); pair with the other organism's "
                    "outcome for the tradeoff framing.")
        return ("**Mixed** — gap is in the 3–9 align band; pair with the "
                "other organism's outcome for the tradeoff framing.")
    if gap < 0:
        return ("**TXC win** — TXC strictly beats SAE-arditi by > 9 align "
                "(unusual; check the per-cell coherence floor — Wang stage 4 "
                "doesn't apply one).")
    return ("**Honest negative** — TXC-base+brickenauxk does not close the "
            "gap; SAE arditi wins on this organism.")


def _peak_dict(rs):
    """Pick the latest-by-ts row in a list and unpack peak fields."""
    if not rs:
        return None
    rs = sorted(rs, key=lambda r: r.ts, reverse=True)
    m = rs[0].metrics
    return {
        "peak_align": float(m.get("peak_align", 0.0) or 0.0),
        "peak_coh": float(m.get("peak_coh", 0.0) or 0.0),
        "peak_alpha": float(m.get("peak_alpha", 0.0) or 0.0),
        "peak_feature_id": int(m.get("peak_feature_id", -1) or -1),
        "ts": rs[0].ts,
        "train_key": rs[0].train_key,
        "eval_key": rs[0].eval_key,
        "seed": int(rs[0].seed),
        "datasource": rs[0].datasource,
        "eval_protocol_version": rs[0].eval_protocol_version,
    }


def _gap_table(paired: list[dict], *, label: str) -> list[str]:
    """Render the per-organism gap table.

    Format mirrors em_prior's `align / coh` paired reporting: the
    paper-relevant tradeoff is that TXC tends to win on align while
    SAE tends to win on coh. Both numbers are surfaced per cell so
    reviewers see the full picture, not just the align-only headline.

    coh_gap = SAE coh − TXC coh; positive = SAE more coherent.
    """
    md = ["",
          f"### {label} (n={len(paired)} paired seeds)",
          "",
          "| seed | SAE align/coh | TXC align/coh | align gap | coh gap | SAE feat α | TXC feat α |",
          "|---:|:---|:---|---:|---:|:---|:---|"]
    align_gaps = []
    coh_gaps = []
    for p in paired:
        sae_a = p["sae"]["peak_align"]
        sae_c = p["sae"]["peak_coh"]
        txc_a = p["txc"]["peak_align"]
        txc_c = p["txc"]["peak_coh"]
        align_gap = sae_a - txc_a
        coh_gap = sae_c - txc_c
        align_gaps.append(align_gap)
        coh_gaps.append(coh_gap)
        md.append(
            f"| {p['seed']} | "
            f"{sae_a:.2f} / {sae_c:.2f} | "
            f"{txc_a:.2f} / {txc_c:.2f} | "
            f"{align_gap:+.2f} | {coh_gap:+.2f} | "
            f"{p['sae']['peak_feature_id']} α={p['sae']['peak_alpha']:+g} | "
            f"{p['txc']['peak_feature_id']} α={p['txc']['peak_alpha']:+g} |"
        )
    if len(align_gaps) >= 2:
        mean_align_gap = sum(align_gaps) / len(align_gaps)
        mean_coh_gap = sum(coh_gaps) / len(coh_gaps)
        align_spread = max(align_gaps) - min(align_gaps)
        coh_spread = max(coh_gaps) - min(coh_gaps)
        md.append("")
        md.append(
            f"**Mean align gap** = {mean_align_gap:+.2f} "
            f"(spread {align_spread:.2f}). "
            f"**Mean coh gap** = {mean_coh_gap:+.2f} "
            f"(spread {coh_spread:.2f}). "
            f"Decision (align): {_decision(mean_align_gap)}"
        )
        if mean_coh_gap > 3.0:
            md.append("")
            md.append(
                f"_Coherence tradeoff_: SAE-arditi peaks at {mean_coh_gap:+.2f} "
                f"coh higher than TXC-base on average. TXC's align gain comes "
                f"at the cost of some coherence — the canonical-reading: "
                f"TXC steers toward misalignment more aggressively, sacrificing "
                f"coherence at the peak. Reviewers comparing arches should "
                f"weight both axes."
            )
    elif len(align_gaps) == 1:
        md.append("")
        md.append(
            f"single-seed align gap = {align_gaps[0]:+.2f}, coh gap = "
            f"{coh_gaps[0]:+.2f}. Decision (align): {_decision(align_gaps[0])}"
        )
    return md


def _detection_rows_by_organism(
    rows: list, valid_train_keys: set[str],
) -> dict[str, list[dict]]:
    """Group eval_protocol_version=3.0.0 rows by organism label.

    Each cell is one (arch, seed) within an organism. Returns a dict
    keyed by ORGANISM_BY_DATASOURCE label, value is a list of dicts:
    ``{seed, arch, pr_auc_S{1..32}, pr_auc_shuffled_S{1..32},
       shuffle_gap_S{1..32}, n_sent, positive_rate, train_key,
       eval_key, ts}``.
    """
    by_org: dict[str, list[dict]] = {org: [] for org in ORGANISM_BY_DATASOURCE.values()}
    for r in rows:
        if r.eval_protocol_version != DETECTION_PROTOCOL:
            continue
        if r.train_key not in valid_train_keys:
            continue
        org = ORGANISM_BY_DATASOURCE.get(r.datasource)
        if org is None:
            continue
        m = r.metrics
        cell = {
            "seed": int(r.seed),
            "arch": r.arch,
            "n_sent": float(m.get("n_sent", 0)),
            "positive_rate": float(m.get("positive_rate", 0)),
            "train_key": r.train_key,
            "eval_key": r.eval_key,
            "ts": r.ts,
        }
        for s in (1, 2, 4, 8, 16, 32):
            cell[f"pr_auc_S{s}"] = float(m.get(f"pr_auc_S{s}", float("nan")))
            cell[f"pr_auc_shuffled_S{s}"] = float(m.get(f"pr_auc_shuffled_S{s}", float("nan")))
            cell[f"shuffle_gap_S{s}"] = float(m.get(f"shuffle_gap_S{s}", float("nan")))
        by_org[org].append(cell)
    return by_org


def _detection_table_md(by_org: dict[str, list[dict]]) -> list[str]:
    """Render a detection PR-AUC table per organism + a means summary.

    Convention: PR-AUC at S∈{1,2,4,8,16,32}, headline cell is S=16
    (matches C7 paper convention). Per-cell row format:
      | seed | arch | n_sent | pos_rate | PR-AUC@S=16 | shuffle_gap@S=16 |
    Plus a per-arch mean across seeds, and a SAE-vs-TXC paired delta.
    """
    md = []
    if not any(by_org.values()):
        return md
    md += ["", "### Detection PR-AUC (eval_protocol_version=3.0.0)", "",
           "Sparse-probe detection asks *can a linear probe over the "
           "arch's features distinguish misaligned (Sonnet judge "
           "`align ≤ 50`) from aligned rollouts*. Cohort: 1.7-2k stage-4 "
           "rollouts per cell (balanced α grid spanning -100 to +100), "
           "stride-1 T-windows propagated to the parent rollout's label, "
           "GroupKFold-by-prompt at 5 folds. Within-window shuffle "
           "ablation reports whether temporal structure adds detection "
           f"signal. Random PR-AUC = positive_rate. Headline S = "
           f"{DETECTION_S_HEADLINE}.",
           ""]
    for org, cells in by_org.items():
        if not cells:
            continue
        md += ["", f"#### {org}", "",
               "| seed | arch | n_sent | positive_rate | "
               f"PR-AUC@S={DETECTION_S_HEADLINE} | "
               f"shuffled@S={DETECTION_S_HEADLINE} | "
               f"shuffle_gap@S={DETECTION_S_HEADLINE} |",
               "|---:|:---|---:|---:|---:|---:|---:|"]
        # Sort by (arch, seed) for stable rendering.
        cells_sorted = sorted(cells, key=lambda c: (c["arch"], c["seed"]))
        # Per-cell rows. For per-token archs (SAE T=1), the shuffle
        # ablation is not applicable — there's nothing to shuffle
        # within a single-position window. Render those cells as "—".
        import math
        for c in cells_sorted:
            S = DETECTION_S_HEADLINE
            sh = c[f"pr_auc_shuffled_S{S}"]
            sg = c[f"shuffle_gap_S{S}"]
            sh_str = f"{sh:.3f}" if not math.isnan(sh) else "— (T=1)"
            sg_str = f"{sg:+.3f}" if not math.isnan(sg) else "—"
            md.append(
                f"| {c['seed']} | {c['arch']} | {int(c['n_sent'])} | "
                f"{c['positive_rate']:.3f} | "
                f"{c[f'pr_auc_S{S}']:.3f} | "
                f"{sh_str} | {sg_str} |"
            )
        # Per-arch means + SAE-TXC delta.
        archs = sorted(set(c["arch"] for c in cells_sorted))
        if len(archs) >= 2:
            S = DETECTION_S_HEADLINE
            arch_means: dict[str, float] = {}
            for arch in archs:
                vs = [c[f"pr_auc_S{S}"] for c in cells_sorted if c["arch"] == arch]
                if vs:
                    arch_means[arch] = sum(vs) / len(vs)
            md.append("")
            md.append(
                f"**Per-arch mean PR-AUC@S={S}** (n=2 paired seeds): "
                + ", ".join(f"`{a}`={v:.3f}" for a, v in arch_means.items())
            )
            if "sae_arditi" in arch_means and "txc_base" in arch_means:
                detect_gap = arch_means["sae_arditi"] - arch_means["txc_base"]
                better = "SAE-arditi" if detect_gap > 0 else "TXC-base"
                md.append(
                    f"Detection gap (SAE − TXC) = {detect_gap:+.3f}. "
                    f"**{better}** wins detection on this organism."
                )
    return md


def run_analysis() -> AnalysisResult:
    rows = query_leaderboard(component=COMPONENT)
    if not rows:
        return AnalysisResult(
            markdown=_placeholder("no C6 cells in `results/leaderboard.jsonl` yet."),
            results={},
            plot_paths=[],
        )

    # Filter to canonical-config cells (decisions.md § 12 — drop pre-
    # 2026-05-04 batch=256 rows). 1.0.0 abbreviated rows happen to also
    # be batch=256 by my pipeline so they get dropped here too, but the
    # eval_protocol_version filter below makes that explicit either way.
    valid_train_keys = _canonical_keys()
    rows = [r for r in rows if r.train_key in valid_train_keys]
    if not rows:
        return AnalysisResult(
            markdown=_placeholder(
                "no canonical-config C6 cells run yet — see "
                "experiments/c6_em/run.py (TrainingConfig defaults: "
                "batch=1024, n_steps=25_000, plateau_off per decisions.md § 12; "
                "txc_base also overrides bricken_enabled=True, "
                "ema_auxk_alpha=1/8, dead_threshold_tokens=128_000 per § 7)."
            ),
            results={},
            plot_paths=[],
        )

    # Filter to full-Wang (headline) rows. 1.0.0 abbreviated rows are
    # preserved in the leaderboard but never make it into the headline.
    full_rows = [r for r in rows if r.eval_protocol_version == HEADLINE_PROTOCOL]
    abbr_rows = [r for r in rows if r.eval_protocol_version == "1.0.0"]

    if not full_rows:
        # Pre-headline state: render an interim block that explicitly
        # flags the situation rather than producing misleading numbers.
        md = [
            "_(Auto-generated by `experiments/c6_em/analysis.py`. Do not hand-edit "
            "between AUTO-RESULTS markers.)_\n",
            f"**Status: pre-headline.** No `eval_protocol_version={HEADLINE_PROTOCOL}` "
            f"(full Wang) cells have landed yet — only "
            f"{len(abbr_rows)} legacy abbreviated-Wang rows. The abbreviated "
            "headline (mean gap +3.79 align, paper-correct 14B finance, n=3 "
            "seeds) does NOT satisfy c6.md *Setup*'s 4-stage Wang spec and is "
            "deliberately suppressed here to avoid being cited as the headline.",
            "",
            f"Run `python -m experiments.c6_em.run --seed {HEADLINE_SEED}` "
            "(14B finance) and `python -m experiments.c6_em.run "
            "--datasource qwen_2_5_7b_instruct_medical_l15_resid_post "
            f"--seed {HEADLINE_SEED}` (7B medical) to populate the headline.",
        ]
        return AnalysisResult(
            markdown="\n".join(md) + "\n",
            results={"abbreviated_rows": len(abbr_rows), "full_rows": 0},
            plot_paths=[],
        )

    # Group rows by (datasource, arch, seed) so we can pair SAE / TXC per organism.
    by_key: dict[tuple[str, str, int], list] = {}
    for r in full_rows:
        by_key.setdefault((r.datasource, r.arch, int(r.seed)), []).append(r)

    # Per-organism: collect paired (sae, txc) per seed.
    organism_results: dict[str, dict] = {}
    for ds_name, organism_label in ORGANISM_BY_DATASOURCE.items():
        seeds_here = sorted({s for (d, _a, s) in by_key if d == ds_name})
        paired = []
        for seed in seeds_here:
            sae_p = _peak_dict(by_key.get((ds_name, "sae_arditi", seed), []))
            txc_p = _peak_dict(by_key.get((ds_name, "txc_base", seed), []))
            if sae_p and txc_p:
                paired.append({
                    "seed": seed, "sae": sae_p, "txc": txc_p,
                    "gap": sae_p["peak_align"] - txc_p["peak_align"],
                })
        organism_results[organism_label] = {
            "datasource": ds_name,
            "paired": paired,
            "any_sae": any(_peak_dict(by_key.get((ds_name, "sae_arditi", s), []))
                           for s in seeds_here),
            "any_txc": any(_peak_dict(by_key.get((ds_name, "txc_base", s), []))
                           for s in seeds_here),
        }

    md_lines = [
        "_(Auto-generated by `experiments/c6_em/analysis.py`. Do not hand-edit "
        "between AUTO-RESULTS markers. The 'Existing evidence' section above is "
        "hand-curated reference data from `origin/case-em-prior` and stays static — "
        "this block is for the locked-arch + brickenauxk full-Wang re-test "
        "outcome.)_\n",
        f"### Full Wang (eval_protocol_version={HEADLINE_PROTOCOL})\n",
        "Caveats baked into this run:",
        "",
        "- **Judge**: Anthropic Claude Haiku 4.5 (per (decision 2026-05-04) — Gemini "
        "stays wasteland reference; raw judge_outputs.jsonl persisted per cell "
        "for post-deadline κ validation if reviewers ask).",
        "- **Wang**: full 4 stages — Δz̄ rank (top-100) → causal screen at α=±1 "
        "(top-20 survivors) → per-survivor coh-aware sweep (top-3 finalists) → "
        "27-α frontier on top-3.",
        "- **Corpora (HF stand-ins)**: "
        "`cfierro/personality-qs-risky-financial-advice` (14B-finance), "
        "`cfierro/personality-qs-bad-medical-advice` (7B-medical). Turner's "
        "exact local files are not on HF.",
        "- **Hparams**: TXC-base uses the `c6` per-component override "
        "(`d_sae=32768, k_pos=25, k_win=125`); SAE-arditi uses the locked "
        "default (`d_sae=32768, k_pos=128`). Both are paper-correct.",
        "",
        "Absolute peak_align is NOT directly comparable to the prior author's published "
        "Gemini-judged numbers. The **relative gap per organism** is the "
        "headline.",
    ]

    plot_paths: list[Path] = []
    headline_gaps_for_results: dict[str, float | None] = {}

    for organism_label, res in organism_results.items():
        paired = res["paired"]
        ds_name = res["datasource"]
        if not paired:
            md_lines += [
                "",
                f"#### {organism_label}",
                "",
                f"_No paired full-Wang cells yet for `{ds_name}` — run "
                f"`python -m experiments.c6_em.run --datasource {ds_name} --seed N`._",
            ]
            headline_gaps_for_results[organism_label] = None
            continue

        md_lines += _gap_table(
            paired,
            label=f"{organism_label} ({ds_name})",
        )
        if len(paired) >= 1:
            gaps = [p["gap"] for p in paired]
            mean_gap = sum(gaps) / len(gaps)
            coh_gaps = [p["sae"]["peak_coh"] - p["txc"]["peak_coh"]
                        for p in paired]
            mean_coh_gap = sum(coh_gaps) / len(coh_gaps)
            headline_gaps_for_results[organism_label] = (mean_gap, mean_coh_gap)
        else:
            headline_gaps_for_results[organism_label] = None

        # Pareto scatter (coherence × alignment) using ALL paired seeds'
        # stage-4 cells. Replaces the prior α-line frontier plot.
        # Two versions: full distribution + main-cluster (outliers dropped).
        sae_wangs = [
            w for p in paired
            if (w := _read_wang_full(p["sae"]["train_key"])) is not None
        ]
        txc_wangs = [
            w for p in paired
            if (w := _read_wang_full(p["txc"]["train_key"])) is not None
        ]
        org_slug = organism_label.lower().replace('-', '_')
        for is_filtered, suffix, label_suffix in (
            (False, "", ""),
            (True, "_clustered", " — main cluster only"),
        ):
            plot_dst = PLOT_DIR / f"c6_pareto_{org_slug}{suffix}.png"
            try:
                saved = _save_pareto_scatter(
                    sae_wangs, txc_wangs, dst=plot_dst,
                    organism_label=organism_label,
                    filter_outliers=is_filtered,
                )
            except Exception:
                saved = None
            if saved is not None:
                plot_paths.append(saved)
                md_lines += [
                    "",
                    f"![C6 Pareto scatter — {organism_label}{label_suffix}]"
                    f"(../../experiments/c6_em/plots/{plot_dst.name})",
                ]

    # If both organisms landed, also write a one-line headline pairing.
    fin = headline_gaps_for_results.get("14B-finance")
    med = headline_gaps_for_results.get("7B-medical")
    if fin is not None and med is not None:
        fin_align, fin_coh = fin
        med_align, med_coh = med
        md_lines += [
            "",
            "### Headline pairing (align / coh, both axes)",
            "",
            f"- **14B-finance** (n={len(organism_results['14B-finance']['paired'])}): "
            f"align gap {fin_align:+.2f} / coh gap {fin_coh:+.2f} — "
            f"{_decision(fin_align).split('—')[0].strip()}",
            f"- **7B-medical** (n={len(organism_results['7B-medical']['paired'])}): "
            f"align gap {med_align:+.2f} / coh gap {med_coh:+.2f} — "
            f"{_decision(med_align).split('—')[0].strip()}",
            "",
            "(Negative align gap = TXC > SAE on alignment. Positive coh gap = "
            "SAE > TXC on coherence. The c6.md decision tree is keyed on "
            "|align gap|; coh gap is the tradeoff axis — TXC's align win comes "
            "with some coherence cost.)",
        ]

    # ── Detection PR-AUC (eval_protocol_version=3.0.0) ──
    # Surface the C6 detection axis ((decision 2026-05-05)) alongside
    # the steering axis. Detection cells are written by
    # experiments.c6_em_detection.run; they share the canonical
    # train_keys (cache-hit on training).
    detection_by_org = _detection_rows_by_organism(
        # Re-query ALL rows (including 3.0.0) because the existing
        # filter above keeps only HEADLINE_PROTOCOL=2.0.0 rows.
        query_leaderboard(component=COMPONENT),
        valid_train_keys,
    )
    md_lines += _detection_table_md(detection_by_org)

    if abbr_rows:
        md_lines += [
            "",
            f"### Abbreviated-Wang (eval_protocol_version=1.0.0) — diff reference only\n",
            f"_{len(abbr_rows)} legacy rows from the 2026-05-03 abbreviated-Wang "
            "preliminary runs are preserved in the leaderboard for "
            "diff-against-full comparison only — they do NOT factor into the "
            "headline. See `git log -p docs/components/c6.md` for the prior "
            "AUTO-RESULTS rendering._",
        ]

    results = {
        "headline_protocol": HEADLINE_PROTOCOL,
        "n_full_rows": len(full_rows),
        "n_abbreviated_rows": len(abbr_rows),
        "per_organism": {
            org: {
                "datasource": data["datasource"],
                "n_paired": len(data["paired"]),
                "mean_gap": (
                    sum(p["gap"] for p in data["paired"]) / len(data["paired"])
                    if data["paired"] else None
                ),
                "mean_coh_gap": (
                    sum(p["sae"]["peak_coh"] - p["txc"]["peak_coh"]
                        for p in data["paired"]) / len(data["paired"])
                    if data["paired"] else None
                ),
                "paired": [
                    {
                        "seed": p["seed"],
                        "gap": p["gap"],
                        "coh_gap": p["sae"]["peak_coh"] - p["txc"]["peak_coh"],
                        "sae_peak_align": p["sae"]["peak_align"],
                        "sae_peak_coh": p["sae"]["peak_coh"],
                        "txc_peak_align": p["txc"]["peak_align"],
                        "txc_peak_coh": p["txc"]["peak_coh"],
                        "sae_train_key": p["sae"]["train_key"],
                        "txc_train_key": p["txc"]["train_key"],
                    }
                    for p in data["paired"]
                ],
            }
            for org, data in organism_results.items()
        },
        "detection_by_organism": {
            org: [
                {k: v for k, v in c.items() if k != "ts"}
                for c in cells
            ]
            for org, cells in detection_by_org.items()
        },
    }
    return AnalysisResult(
        markdown="\n".join(md_lines) + "\n",
        results=results,
        plot_paths=plot_paths,
    )
