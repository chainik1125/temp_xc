"""Per-component analysis template — copy into ``experiments/cN_*/analysis.py``.

A component's ``analysis.py`` is the **only** place that reads the
leaderboard for paper-relevant numbers and turns them into prose. The
``Results`` section of ``docs/components/cN.md`` (between
``<!-- BEGIN AUTO-RESULTS -->`` and ``<!-- END AUTO-RESULTS -->``) is
rewritten by ``temp_bench.report.render(component=...)`` from the
return value here. Hand-editing between the markers is forbidden — see
``PROTOCOL.md`` § 7 *Results live in state*.

Workflow:
    1. ``run_analysis()`` queries leaderboard rows for this component.
    2. Computes summary numbers (peaks, means ± seed σ, frontiers).
    3. Saves aggregate plots to ``experiments/cN_*/plots/`` via
       :func:`temp_bench.plotting.save_figure`.
    4. Returns an :class:`AnalysisResult` with:
         - ``markdown``: content for the AUTO-RESULTS block (tables,
           image links, narrative).
         - ``results``: structured dict dumped to ``results.json``.
         - ``plot_paths``: list of plot paths recorded for the renderer.

Edge cases the template handles cleanly:
    - **No cells yet**: return a placeholder markdown that says
      "no cells run yet" rather than crashing. agent_paper / human can
      then re-run after first cells land.
    - **Partial sweep**: explicitly say which seeds / archs are missing.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt

from temp_bench.plotting import save_figure
from temp_bench.report import AnalysisResult, query_leaderboard

# ── Edit these per component ────────────────────────────────────────────

COMPONENT = "cN"                                  # "c1", "c2", ..., "c7"
EXP_DIR = Path(__file__).parent                   # experiments/cN_*/
PLOT_DIR = EXP_DIR / "plots"


def _placeholder_markdown(reason: str) -> str:
    return (
        "_(Auto-generated by `experiments/" + EXP_DIR.name + "/analysis.py` — "
        "do not hand-edit between AUTO-RESULTS markers.)_\n\n"
        f"No results yet: {reason}\n"
    )


def run_analysis() -> AnalysisResult:
    """Compute headlines + plots for this component.

    Replace the body with your component's logic. The general pattern:

        rows = query_leaderboard(component=COMPONENT)
        if not rows:
            return AnalysisResult(markdown=_placeholder_markdown("no cells yet"))

        # Aggregate by (arch, seed) → mean ± stderr
        ...

        # Save aggregate plots
        PLOT_DIR.mkdir(parents=True, exist_ok=True)
        fig, ax = plt.subplots()
        ax.plot(...)
        save_figure(fig, PLOT_DIR / "headline.png")

        # Build markdown table
        md = (
            "| arch | mean | σ_seeds |\n"
            "|---|---:|---:|\n"
            f"| txc_pro | {peak:.4f} | {sigma:.4f} |\n"
            f"\n![sparsity curves](../../experiments/{EXP_DIR.name}/plots/headline.png)\n"
        )

        return AnalysisResult(
            markdown=md,
            results={"txc_pro": {"peak": peak, "sigma": sigma}},
            plot_paths=[PLOT_DIR / "headline.png"],
        )
    """
    rows = query_leaderboard(component=COMPONENT)
    if not rows:
        return AnalysisResult(
            markdown=_placeholder_markdown("no cells run yet"),
            results={},
            plot_paths=[],
        )

    # Default fallback: just count rows, group by arch+seed.
    # Replace with your component's real analysis.
    by_arch: dict[str, list[float]] = {}
    primary = rows[0].primary_metric
    for r in rows:
        by_arch.setdefault(r.arch, []).append(r.metrics.get(primary, float("nan")))
    md_lines = [
        "_(Auto-generated — placeholder summary; replace with real analysis.)_\n",
        f"| arch | n_cells | mean({primary}) |",
        "|---|---:|---:|",
    ]
    results: dict = {}
    for arch, vals in sorted(by_arch.items()):
        m = sum(vals) / len(vals) if vals else float("nan")
        md_lines.append(f"| {arch} | {len(vals)} | {m:.4f} |")
        results[arch] = {"n_cells": len(vals), f"mean_{primary}": m}
    return AnalysisResult(
        markdown="\n".join(md_lines) + "\n",
        results=results,
        plot_paths=[],
    )
