"""C3 BASE replication analysis — leaderboard → results.json + plots.

Mirrors ``experiments/c3_probing/analysis.py`` (agent_nlp's IT side)
arch-for-arch but filters on the BASE datasource. agent_paper picks
up ``results.json`` at paper-render time and integrates BASE alongside
IT in ``docs/components/c3.md``.

Run via either::

    .venv/bin/python -c "from temp_bench import report; report.render(component='c3-base')"

or directly::

    .venv/bin/python -m experiments.c3_probing_base.analysis

Aggregation policy (matches IT):
- Filter ``smoke=True`` rows out.
- Headline metric = ``mean_auc`` (38-task SAEBench+CT mean).
- Per (arch, k_feat): mean ± σ_seeds across seeds {1, 2, 42}.
- Per (arch, k_feat): mean σ_tasks across seeds (intra-cell spread).
- Plot: AUC vs k_feat per arch with σ_seeds bars.
- Sweep: k_feats ∈ {5, 10, 20, 40, 80, 160, 320, 640} ((decision 2026-05-06)).
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev

import matplotlib.pyplot as plt

from temp_bench.plotting import save_figure
from temp_bench.report import AnalysisResult, canonical_train_keys, query_leaderboard
from temp_bench.schemas import TrainingConfig

COMPONENT = "c3"
EXP_DIR = Path(__file__).parent
PLOT_DIR = EXP_DIR / "plots"

# BASE datasource — only thing that differs vs IT side.
DATASOURCE_NAME = "gemma_2_2b_base_l13_fineweb_24k128"
DATASOURCE_NAME_MULTILAYER = "gemma_2_2b_base_l11to15_fineweb_24k128"

TXC_ARCHS = ("txc_base", "txc_pro")
TOPK_ARCHS = ("topk_sae",)
TSAE_ARCHS = ("tsae_paper",)
TFA_ARCHS = ("tfa",)
MLC_ARCHS = ("mlc",)
HEADLINE_ARCHS = TXC_ARCHS + TOPK_ARCHS + TSAE_ARCHS + TFA_ARCHS + MLC_ARCHS
HEADLINE_SEEDS = (1, 2, 42)
HEADLINE_EVAL_PROTOCOL_VERSION = "1.1.0"


def _placeholder_markdown(reason: str) -> str:
    return (
        "_(Auto-generated by `experiments/c3_probing_base/analysis.py` — do not "
        "hand-edit.)_\n\n"
        f"No BASE headline yet: {reason}\n"
    )


def run_analysis() -> AnalysisResult:
    rows = query_leaderboard(component=COMPONENT, datasource=DATASOURCE_NAME)

    # Canonical train_key filter — same per-arch families as IT side
    # (decisions.md § 15 + § 16). Plus the § 17 T-sweep cells for
    # txc_base × {T=10, T=20} (agent_filler runs these on BASE).
    txc_keys = canonical_train_keys(
        component=COMPONENT,
        archs=TXC_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000),
    )
    topk_keys = canonical_train_keys(
        component=COMPONENT,
        archs=TOPK_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=1),
    )
    tsae_keys = canonical_train_keys(
        component=COMPONENT,
        archs=TSAE_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=2),
    )
    tfa_keys = canonical_train_keys(
        component=COMPONENT,
        archs=TFA_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, batch_size=32),
    )
    mlc_keys = canonical_train_keys(
        component=COMPONENT,
        archs=MLC_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME_MULTILAYER,),
        training_cfg=TrainingConfig(n_steps=20_000),
    )
    # T-sweep cells (decisions § 17): txc_base × {T=10, T=20}.
    # canonical_train_keys doesn't replicate the runner's
    # arch_hparams_override merge into spec.hparams; do it ourselves.
    txc_T_keys: set[str] = set()
    from temp_bench.config import (
        compute_act_cache_key, compute_train_key, load_arch, load_datasource,
    )
    ack = compute_act_cache_key(load_datasource(DATASOURCE_NAME))
    txc_base_spec = load_arch("txc_base", component=COMPONENT)
    for T in (10, 20):
        merged = {**txc_base_spec.hparams, "T": T}
        spec = txc_base_spec.model_copy(update={"hparams": merged})
        for seed in HEADLINE_SEEDS:
            txc_T_keys.add(compute_train_key(
                arch=spec, seed=seed,
                training_cfg=TrainingConfig(
                    n_steps=20_000, arch_hparams_override={"T": T},
                ),
                act_cache_key=ack,
            ))
    valid_keys = txc_keys | topk_keys | tsae_keys | tfa_keys | mlc_keys | txc_T_keys

    real_rows = [
        r for r in rows
        if not r.eval_cfg.get("smoke", False)
        and r.eval_protocol_version == HEADLINE_EVAL_PROTOCOL_VERSION
        and r.train_key in valid_keys
    ]

    if not real_rows:
        n_smoke = len(rows)
        return AnalysisResult(
            markdown=_placeholder_markdown(
                f"no real BASE cells yet ({n_smoke} smoke/non-canonical row(s) "
                f"filtered out)."
            ),
            results={"n_smoke_rows": n_smoke},
            plot_paths=[],
        )

    # Group: (arch, k_feat) → list of {seed, mean_auc, ...}
    grouped: dict[tuple[str, int], list[dict]] = defaultdict(list)
    for r in real_rows:
        k = int(r.eval_cfg.get("k_feat", -1))
        if k < 0:
            continue
        if "mean_auc" not in r.metrics:
            continue
        grouped[(r.arch, k)].append({
            "seed": r.seed,
            "mean_auc": float(r.metrics["mean_auc"]),
            "std_auc": float(r.metrics.get("std_auc", 0.0)),
            "mean_acc": float(r.metrics.get("mean_acc", 0.0)),
            "n_tasks": int(r.metrics.get("n_tasks", 0)),
        })

    # Aggregate across seeds
    summary: dict[str, dict] = {}
    for (arch, k_feat), cells in sorted(grouped.items()):
        aucs = [c["mean_auc"] for c in cells]
        accs = [c["mean_acc"] for c in cells]
        std_tasks = [c["std_auc"] for c in cells]
        n_tasks_seen = max((c["n_tasks"] for c in cells), default=0)
        agg = {
            "n_seeds": len(cells),
            "seeds": sorted({c["seed"] for c in cells}),
            "mean_auc": float(mean(aucs)),
            "std_seeds_auc": float(stdev(aucs)) if len(aucs) > 1 else 0.0,
            "mean_acc": float(mean(accs)),
            "std_seeds_acc": float(stdev(accs)) if len(accs) > 1 else 0.0,
            "mean_std_tasks_auc": float(mean(std_tasks)) if std_tasks else 0.0,
            "n_tasks": n_tasks_seen,
        }
        summary.setdefault(arch, {})[f"k{k_feat}"] = agg

    # ── Plot: AUC vs k_feat
    PLOT_DIR.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(7, 5))
    arch_order = [a for a in HEADLINE_ARCHS if a in summary]
    colour_map = {
        "topk_sae": "tab:blue",
        "tsae_paper": "tab:orange",
        "tfa": "tab:red",
        "txc_base": "tab:green",
        "txc_pro": "tab:purple",
        "mlc": "tab:brown",
    }
    for arch in arch_order:
        ks = sorted(int(kk[1:]) for kk in summary[arch])
        means = [summary[arch][f"k{k}"]["mean_auc"] for k in ks]
        sigmas = [summary[arch][f"k{k}"]["std_seeds_auc"] for k in ks]
        ax.errorbar(
            ks, means, yerr=sigmas, marker="o", capsize=3,
            color=colour_map.get(arch), label=arch,
        )
    ax.set_xscale("log")
    ax.set_xlabel("k_feat (probe top-k features)")
    ax.set_ylabel("mean AUC (38-task SAEBench+CT)")
    ax.set_title(
        f"C3 BASE — sparse probing, {DATASOURCE_NAME}\n"
        "subject = google/gemma-2-2b (NOT -it)",
        fontsize=10,
    )
    ax.legend(loc="lower right", fontsize=9)
    ax.grid(alpha=0.3)
    plot_path = PLOT_DIR / "auc_by_k_base.png"
    save_figure(fig, plot_path)
    plt.close(fig)

    # ── Markdown
    n_tasks = max(
        (
            v["n_tasks"]
            for arch_summary in summary.values()
            for v in arch_summary.values()
        ),
        default=38,
    )
    all_ks = sorted({int(kk[1:]) for arch_summary in summary.values() for kk in arch_summary})

    md_lines = [
        "_(Auto-generated by `experiments/c3_probing_base/analysis.py` — "
        "do not hand-edit. Mirrors `experiments/c3_probing/` arch-for-arch "
        "with the BASE Gemma datasource. agent_paper integrates IT + BASE "
        "at paper-render time.)_",
        "",
        f"Subject: `google/gemma-2-2b` (BASE, NOT `-it`). Layer 13.",
        f"Task suite: SAEBench+CT (n={n_tasks}). "
        f"Aggregation: mean over seeds, then over tasks. "
        f"Seeds: {list(HEADLINE_SEEDS)}. "
        f"k_feats: {all_ks}.",
        "",
    ]
    if all_ks:
        header = "| arch | " + " | ".join(f"k={k}" for k in all_ks) + " |"
        sep = "|---|" + "|".join("---:" for _ in all_ks) + "|"
        md_lines.append(header)
        md_lines.append(sep)
        for arch in arch_order:
            cells = summary[arch]
            row = [arch]
            for k in all_ks:
                key = f"k{k}"
                if key in cells:
                    a = cells[key]
                    row.append(f"{a['mean_auc']:.4f}±{a['std_seeds_auc']:.4f}")
                else:
                    row.append("—")
            md_lines.append("| " + " | ".join(row) + " |")
        md_lines.append("")
    md_lines.append(
        f"![AUC vs k_feat — BASE](../../experiments/{EXP_DIR.name}/plots/{plot_path.name})"
    )
    md = "\n".join(md_lines) + "\n"

    return AnalysisResult(
        markdown=md,
        results={
            "datasource": DATASOURCE_NAME,
            "subject_model": "google/gemma-2-2b",
            "headline_eval_protocol_version": HEADLINE_EVAL_PROTOCOL_VERSION,
            "by_arch": summary,
            "n_real_rows": len(real_rows),
            "k_feats": all_ks,
        },
        plot_paths=[plot_path.relative_to(EXP_DIR.parent.parent)],
    )


def main():
    result = run_analysis()
    import json
    out_path = EXP_DIR / "results.json"
    out_path.write_text(json.dumps(result.results, indent=2))
    print(f"[c3_probing_base.analysis] wrote {out_path} "
          f"(n_real_rows={result.results.get('n_real_rows', 0)})")
    md_preview = result.markdown[:500] + ("..." if len(result.markdown) > 500 else "")
    print(f"\n--- markdown preview ---\n{md_preview}")


if __name__ == "__main__":
    main()
