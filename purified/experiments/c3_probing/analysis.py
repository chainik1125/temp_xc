"""C3 sparse-probing analysis — leaderboard → AUTO-RESULTS block + plots.

Run via either::

    .venv/bin/python -c "from temp_bench import report; report.render(component='c3')"

or directly::

    .venv/bin/python -m experiments.c3_probing.analysis

Aggregation policy (locked in agent_paper/decisions.md):
- Filter ``smoke=True`` rows out (those are pipeline-validation artefacts,
  not paper claims).
- Headline metric = ``mean_auc`` recomputed at analysis time over the 36
  canonical SAEBench tasks (the leaderboard row stores per-task AUCs for
  all 38 incl. winogrande/wsc; the cross-token pair drops at aggregation
  per the c3.md "we report SAEBench-36 only" decision).
- Per (arch, k_feat): mean ± σ_seeds across seeds {1, 2, 42}.
- ``txc_base`` is split into ``txc_base_T5``, ``txc_base_T10``, ``txc_base_T20``
  via train_key lookup (decisions § 17 T-sweep — T values are encoded in the
  train_key, not the arch name).

Plots:
- ``plots/auc_by_k.png`` — paper-ready line plot, log-x k_feat, all archs;
  txc_base T-sweep variants share color with distinct line styles.
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev

import matplotlib.pyplot as plt

from temp_bench.plotting import save_figure
from temp_bench.report import AnalysisResult, canonical_train_keys, query_leaderboard

COMPONENT = "c3"
EXP_DIR = Path(__file__).parent
PLOT_DIR = EXP_DIR / "plots"

# Paper headline = IT only (BASE replication deferred post-deadline).
DATASOURCE_NAME = "gemma_2_2b_it_l13_fineweb_24k128"
DATASOURCE_NAME_MULTILAYER = "gemma_2_2b_it_l11to15_fineweb_24k128"
TXC_ARCHS = ("txc_base", "txc_pro")
TOPK_ARCHS = ("topk_sae",)
TSAE_ARCHS = ("tsae_paper",)
TFA_ARCHS = ("tfa",)
MLC_ARCHS = ("mlc",)
HEADLINE_SEEDS = (1, 2, 42)
HEADLINE_EVAL_PROTOCOL_VERSION = "1.1.0"

# Display labels: maps internal arch label → markdown-friendly arch name.
ARCH_DISPLAY = {
    "mlc":           "MLC",
    "tsae_paper":    "T-SAE",
    "topk_sae":      "TopK-SAE",
    "tfa":           "TFA",
    "txc_pro":       "TXC-pro",
    "txc_base_T5":   "TXC-base (T=5)",
    "txc_base_T10":  "TXC-base (T=10)",
    "txc_base_T20":  "TXC-base (T=20)",
}

# Order for the table + plot legend (top → bottom = best → worst at k=20).
ARCH_ORDER = (
    "mlc", "tsae_paper", "txc_base_T20", "txc_base_T10", "txc_base_T5",
    "txc_pro", "topk_sae", "tfa",
)

# The 2 cross-token tasks dropped from the headline metric. Per-task AUCs
# remain in the leaderboard rows; we just exclude them when computing
# ``mean_auc`` for the SAEBench-36 headline.
CT_TASKS = ("winogrande_correct_completion", "wsc_coreference")
N_HEADLINE_TASKS = 36


def _placeholder_markdown(reason: str) -> str:
    return (
        "_(Auto-generated by `experiments/c3_probing/analysis.py` — do not "
        "hand-edit between AUTO-RESULTS markers.)_\n\n"
        f"No headline yet: {reason}\n"
    )


def _build_canonical_keys() -> tuple[set[str], dict[str, set[str]]]:
    """Return (all_canonical_keys, txc_base_T_keys_by_label).

    The second value lets us map a row's train_key back to the T-variant
    label (``txc_base_T5`` / ``txc_base_T10`` / ``txc_base_T20``).
    """
    from temp_bench.schemas import TrainingConfig
    from temp_bench.config import (
        compute_act_cache_key, compute_train_key, load_arch, load_datasource,
    )

    txc_keys = canonical_train_keys(  # txc_base T=5 default + txc_pro
        component=COMPONENT,
        archs=TXC_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000),
    )
    topk_keys = canonical_train_keys(
        component=COMPONENT,
        archs=TOPK_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=1),
    )
    tsae_keys = canonical_train_keys(
        component=COMPONENT,
        archs=TSAE_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=2),
    )
    tfa_keys = canonical_train_keys(
        component=COMPONENT,
        archs=TFA_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, batch_size=32),
    )
    mlc_keys = canonical_train_keys(
        component=COMPONENT,
        archs=MLC_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME_MULTILAYER,),
        training_cfg=TrainingConfig(n_steps=20_000),
    )

    # T-sweep cells (decisions § 17): txc_base × {T=10, T=20}. Compute
    # train_keys with the merged arch_hparams.
    ack = compute_act_cache_key(load_datasource(DATASOURCE_NAME))
    txc_base_spec = load_arch("txc_base", component=COMPONENT)
    by_T_label: dict[str, set[str]] = {"txc_base_T5": set()}
    # T=5 (default; same set as txc_keys but filtered to txc_base):
    for seed in HEADLINE_SEEDS:
        tk = compute_train_key(
            arch=txc_base_spec, seed=seed,
            training_cfg=TrainingConfig(n_steps=20_000),
            act_cache_key=ack, component=COMPONENT,
        )
        by_T_label["txc_base_T5"].add(tk)
    txc_T_keys: set[str] = set()
    for T in (10, 20):
        merged = {**txc_base_spec.hparams, "T": T}
        spec = txc_base_spec.model_copy(update={"hparams": merged})
        label = f"txc_base_T{T}"
        by_T_label[label] = set()
        for seed in HEADLINE_SEEDS:
            tk = compute_train_key(
                arch=spec, seed=seed,
                training_cfg=TrainingConfig(
                    n_steps=20_000, arch_hparams_override={"T": T},
                ),
                act_cache_key=ack, component=COMPONENT,
            )
            txc_T_keys.add(tk)
            by_T_label[label].add(tk)

    all_keys = txc_keys | topk_keys | tsae_keys | tfa_keys | mlc_keys | txc_T_keys
    return all_keys, by_T_label


def _resolve_arch_label(row, by_T_label: dict[str, set[str]]) -> str:
    """Map a leaderboard row to the display-arch label."""
    if row.arch == "txc_base":
        for label, keys in by_T_label.items():
            if row.train_key in keys:
                return label
        return "txc_base_T5"  # fallback (older default cells)
    return row.arch


def _aggregate_paper_headline(rows) -> tuple[dict[str, dict[int, dict]], int]:
    """Filter IT-side rows + aggregate by (arch_label, k_feat).

    Returns (summary, n_real_rows). ``summary[arch_label][k_feat]`` holds
    the per-cell aggregates (mean_auc, std_seeds, n_seeds, n_tasks, …).
    """
    valid_keys, by_T_label = _build_canonical_keys()

    real_rows = [
        r for r in rows
        if not r.eval_cfg.get("smoke", False)
        and r.eval_protocol_version == HEADLINE_EVAL_PROTOCOL_VERSION
        and r.train_key in valid_keys
    ]

    grouped: dict[tuple[str, int], list[dict]] = defaultdict(list)
    for r in real_rows:
        k = r.eval_cfg.get("k_feat", -1)
        if not isinstance(k, int) or k < 0:
            continue
        # Recompute mean_auc from per-task AUCs with CT_TASKS dropped.
        per_task = {
            key[5:]: float(v) for key, v in r.metrics.items()
            if key.startswith("auc__")
        }
        per_task_36 = {
            tname: v for tname, v in per_task.items() if tname not in CT_TASKS
        }
        if len(per_task_36) < N_HEADLINE_TASKS:
            # Older row missing per-task storage or partial — skip from
            # headline (rare; flagged via std_auc=0 if it slips through).
            continue
        per_task_acc = {
            key[5:]: float(v) for key, v in r.metrics.items()
            if key.startswith("acc__")
        }
        per_task_acc_36 = {
            t: v for t, v in per_task_acc.items() if t not in CT_TASKS
        }
        mean_auc_36 = mean(per_task_36.values())
        std_tasks_36 = stdev(per_task_36.values()) if len(per_task_36) > 1 else 0.0
        mean_acc_36 = (
            mean(per_task_acc_36.values()) if per_task_acc_36 else 0.0
        )
        arch_label = _resolve_arch_label(r, by_T_label)
        grouped[(arch_label, k)].append({
            "seed": r.seed,
            "mean_auc": mean_auc_36,
            "std_auc": std_tasks_36,
            "mean_acc": mean_acc_36,
            "n_tasks": len(per_task_36),
        })

    summary: dict[str, dict[int, dict]] = defaultdict(dict)
    for (arch_label, k_feat), cells in grouped.items():
        # Dedup by seed — keep highest mean_auc if duplicates land on the
        # same (arch_label, k_feat, seed) (can happen across re-runs).
        by_seed: dict[int, dict] = {}
        for c in cells:
            ex = by_seed.get(c["seed"])
            if ex is None or c["mean_auc"] > ex["mean_auc"]:
                by_seed[c["seed"]] = c
        deduped = list(by_seed.values())
        aucs = [c["mean_auc"] for c in deduped]
        accs = [c["mean_acc"] for c in deduped]
        std_tasks = [c["std_auc"] for c in deduped]
        summary[arch_label][k_feat] = {
            "n_seeds": len(deduped),
            "mean_auc": float(mean(aucs)),
            "std_seeds_auc": float(stdev(aucs)) if len(aucs) > 1 else 0.0,
            "mean_acc": float(mean(accs)),
            "mean_std_tasks_auc": float(mean(std_tasks)) if std_tasks else 0.0,
            "n_tasks": max(c["n_tasks"] for c in deduped),
        }

    return summary, len(real_rows)


def run_analysis() -> AnalysisResult:
    rows = query_leaderboard(component=COMPONENT)
    summary, n_real = _aggregate_paper_headline(rows)

    if n_real == 0:
        return AnalysisResult(
            markdown=_placeholder_markdown(
                f"no canonical cells in leaderboard ({len(rows)} total rows)."
            ),
            results={"n_total_rows": len(rows)},
            plot_paths=[],
        )

    all_ks = sorted({k for arch in summary for k in summary[arch]})
    archs_in_summary = [a for a in ARCH_ORDER if a in summary] + \
                       [a for a in summary if a not in ARCH_ORDER]

    md_lines: list[str] = [
        "_(Auto-generated by `experiments/c3_probing/analysis.py`. "
        "See PROTOCOL.md § 7 *Results live in state*.)_",
        "",
        f"Task suite: SAEBench (n={_pick_n(summary)}). "
        f"Subject: `{DATASOURCE_NAME}`. Aggregation: mean over seeds, "
        f"then over tasks. Cross-token tasks (winogrande, wsc) dropped "
        f"from the headline metric — see Caveats.",
        "",
        "**Mean AUC over 36 tasks, by k_feat. Peak = best k_feat "
        "per arch (bold).**",
        "",
        "| arch | " + " | ".join(f"k={k}" for k in all_ks) + " | peak |",
        "|---|" + "|".join(["---:"] * (len(all_ks) + 1)) + "|",
    ]
    for arch_label in archs_in_summary:
        if arch_label not in summary:
            continue
        row_data = summary[arch_label]
        peak_k, peak_v = max(
            ((k, v["mean_auc"]) for k, v in row_data.items()),
            key=lambda t: t[1],
        )
        cells_md = []
        for k in all_ks:
            if k in row_data:
                v = row_data[k]
                val = f"{v['mean_auc']:.3f}"
                if k == peak_k:
                    val = f"**{val}**"
                if v["n_seeds"] < len(HEADLINE_SEEDS):
                    val += f"·{v['n_seeds']}"
                cells_md.append(val)
            else:
                cells_md.append("—")
        peak_label = f"**{peak_v:.3f}** @ k={peak_k}"
        display = ARCH_DISPLAY.get(arch_label, arch_label)
        md_lines.append(
            f"| `{display}` | " + " | ".join(cells_md) + f" | {peak_label} |"
        )
    md_lines.append("")
    md_lines.append(
        "Cells with a `·N` suffix are means over N<3 seeds (in-flight cells; "
        "table will refresh when complete). `—` = no cell yet."
    )
    md_lines.append("")

    # σ_seeds at headline k values
    headline_ks = [k for k in (5, 20, 80, 160, 640) if k in all_ks]
    if headline_ks:
        md_lines.append("**Per-seed σ at headline k_feat values:**")
        md_lines.append("")
        md_lines.append("| arch | " + " | ".join(
            f"k={k} (mean ± σ)" for k in headline_ks
        ) + " |")
        md_lines.append("|---|" + "|".join(["---:"] * len(headline_ks)) + "|")
        for arch_label in archs_in_summary:
            if arch_label not in summary:
                continue
            row_data = summary[arch_label]
            cells_md = []
            for k in headline_ks:
                if k in row_data:
                    v = row_data[k]
                    cells_md.append(
                        f"{v['mean_auc']:.3f} ± {v['std_seeds_auc']:.3f}"
                    )
                else:
                    cells_md.append("—")
            display = ARCH_DISPLAY.get(arch_label, arch_label)
            md_lines.append(f"| `{display}` | " + " | ".join(cells_md) + " |")
        md_lines.append("")

    # Plots — full + TFA-excluded zoom (TFA's 0.65-0.88 range squashes
    # the y-axis on the full plot; excluded view makes the temporal-arch
    # cluster legible).
    PLOT_DIR.mkdir(parents=True, exist_ok=True)
    plot_path = PLOT_DIR / "auc_by_k.png"
    _make_paper_plot(
        summary, plot_path,
        title="C3 — sparse probing on Gemma-2-2B-IT L13",
    )
    plot_path_no_tfa = PLOT_DIR / "auc_by_k_no_tfa.png"
    summary_no_tfa = {
        arch: data for arch, data in summary.items() if arch != "tfa"
    }
    _make_paper_plot(
        summary_no_tfa, plot_path_no_tfa,
        title="C3 — sparse probing (TFA excluded for y-axis zoom)",
    )
    md_lines.append(
        f"![AUC by k_feat — full]"
        f"(../../experiments/{EXP_DIR.name}/plots/auc_by_k.png)"
    )
    md_lines.append("")
    md_lines.append(
        f"![AUC by k_feat — TFA excluded]"
        f"(../../experiments/{EXP_DIR.name}/plots/auc_by_k_no_tfa.png)"
    )
    md_lines.append("")
    md_lines.append(
        "_The second plot drops TFA so the temporal-arch cluster (MLC, "
        "T-SAE, TXC family, TopK-SAE) is legible at finer y-axis scale._"
    )
    md_lines.append("")

    return AnalysisResult(
        markdown="\n".join(md_lines),
        results=dict(summary),
        plot_paths=[plot_path, plot_path_no_tfa],
    )


def _make_paper_plot(summary: dict, path: Path, title: str | None = None) -> None:
    """Paper-ready figure: log-x AUC vs k_feat, all archs, T-sweep family
    visualised via line styles."""
    # Color palette — one per arch family, T-sweep variants share color.
    palette = {
        "mlc":          "#1f77b4",  # blue
        "tsae_paper":   "#9467bd",  # purple
        "topk_sae":     "#ff7f0e",  # orange
        "tfa":          "#d62728",  # red
        "txc_pro":      "#17becf",  # teal
        "txc_base_T5":  "#2ca02c",  # green
        "txc_base_T10": "#2ca02c",
        "txc_base_T20": "#2ca02c",
    }
    linestyle = {
        "txc_base_T5":  "-",
        "txc_base_T10": "--",
        "txc_base_T20": ":",
    }
    marker = {
        "mlc":          "o",
        "tsae_paper":   "s",
        "topk_sae":     "D",
        "tfa":          "v",
        "txc_pro":      "^",
        "txc_base_T5":  "P",
        "txc_base_T10": "P",
        "txc_base_T20": "P",
    }

    fig, ax = plt.subplots(figsize=(7.0, 5.0), dpi=140)

    # Plot in ARCH_ORDER (legend reads top-down by ranking).
    for arch_label in ARCH_ORDER:
        if arch_label not in summary:
            continue
        kpoints = sorted(summary[arch_label].items())
        xs = [k for k, _ in kpoints]
        ys = [v["mean_auc"] for _, v in kpoints]
        es = [v["std_seeds_auc"] for _, v in kpoints]
        ax.errorbar(
            xs, ys, yerr=es,
            color=palette.get(arch_label, "#444"),
            linestyle=linestyle.get(arch_label, "-"),
            marker=marker.get(arch_label, "o"),
            markersize=6,
            linewidth=1.7,
            capsize=3,
            label=ARCH_DISPLAY.get(arch_label, arch_label),
        )

    ax.set_xscale("log")
    ax.set_xticks([5, 10, 20, 40, 80, 160, 320, 640])
    ax.set_xticklabels(["5", "10", "20", "40", "80", "160", "320", "640"])
    ax.set_xlabel("$k_{\\mathrm{feat}}$ (top-k features by class-mean diff)", fontsize=12)
    ax.set_ylabel("Mean AUC across SAEBench (n=36)", fontsize=12)
    ax.set_title(title or "C3 — sparse probing", fontsize=13)
    ax.grid(True, which="both", alpha=0.25, linestyle="-", linewidth=0.5)
    ax.legend(loc="lower right", fontsize=9, framealpha=0.92, ncol=2)
    ax.tick_params(axis="both", labelsize=10)
    fig.tight_layout()
    save_figure(fig, path)


def _pick_n(summary: dict) -> int:
    candidates = []
    for arch_label, by_k in summary.items():
        for agg in by_k.values():
            if agg.get("n_tasks", 0) > 0:
                candidates.append(agg["n_tasks"])
    if not candidates:
        return 38
    from collections import Counter
    return Counter(candidates).most_common(1)[0][0]


