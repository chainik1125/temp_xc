"""C4 BASE replication analysis — leaderboard → results.json + plots.

Mirrors ``experiments/c4_qualitative/analysis.py`` (agent_nlp's IT
side) arch-for-arch but filters on the BASE datasource. agent_paper
integrates IT + BASE at paper-render time.

Run via either::

    .venv/bin/python -c "from temp_bench import report; report.render(component='c4-base')"

or directly::

    .venv/bin/python -m experiments.c4_qualitative_base.analysis

Aggregation policy (matches IT):
- Headline metric = ``top_N_semantic`` (count out of N=256).
- Per (arch, seed): single number; per arch: 3 points across seeds.
- Filter ``smoke=True`` and ``n_features<256`` rows out.
- TFA is excluded — `qualitative.encode_concat_corpus` shape mismatch
  (briefing OQ #2; agent_nlp's IT C4 also excludes TFA from
  ``HEADLINE_ARCHS``).
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev

import matplotlib.pyplot as plt

from temp_bench.plotting import save_figure
from temp_bench.report import AnalysisResult, canonical_train_keys, query_leaderboard
from temp_bench.schemas import TrainingConfig

COMPONENT = "c4"
EXP_DIR = Path(__file__).parent
PLOT_DIR = EXP_DIR / "plots"

DATASOURCE_NAME = "gemma_2_2b_base_l13_fineweb_24k128"   # SHARED with C3 BASE
HEADLINE_ARCHS = ("topk_sae", "tsae_paper", "txc_base", "txc_pro")  # NO TFA
HEADLINE_SEEDS = (1, 2, 42)

C3_TXC_ARCHS = ("txc_base", "txc_pro")
C3_TOPK_ARCHS = ("topk_sae",)
C3_TSAE_ARCHS = ("tsae_paper",)

C4_TXC_ARCHS = ("txc_base", "txc_pro")
C4_TOPK_ARCHS = ("topk_sae",)
C4_TSAE_ARCHS = ("tsae_paper",)


def _placeholder_markdown(reason: str) -> str:
    return (
        "_(Auto-generated by `experiments/c4_qualitative_base/analysis.py` — "
        "do not hand-edit.)_\n\n"
        f"No BASE headline yet: {reason}\n"
    )


def _build_c3_mean_auc_lookup() -> dict[tuple[str, int, int], float]:
    """Return ``(arch, seed, k_feat) -> mean_auc`` from C3 BASE rows."""
    out: dict[tuple[str, int, int], float] = {}
    txc_keys = canonical_train_keys(
        component="c3",
        archs=C3_TXC_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000),
    )
    topk_keys = canonical_train_keys(
        component="c3",
        archs=C3_TOPK_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=1),
    )
    tsae_keys = canonical_train_keys(
        component="c3",
        archs=C3_TSAE_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=2),
    )
    c3_valid_keys = txc_keys | topk_keys | tsae_keys
    for r in query_leaderboard(component="c3", datasource=DATASOURCE_NAME):
        if r.eval_cfg.get("smoke", False):
            continue
        if r.train_key not in c3_valid_keys:
            continue
        if "mean_auc" not in r.metrics:
            continue
        k = int(r.eval_cfg.get("k_feat", -1))
        if k < 0:
            continue
        out[(r.arch, r.seed, k)] = float(r.metrics["mean_auc"])
    return out


def run_analysis() -> AnalysisResult:
    rows = query_leaderboard(component=COMPONENT, datasource=DATASOURCE_NAME)

    # 3 cfg families for C4 BASE: TXC (None), T-SAE (T=2), TopK (T=1).
    # No TFA (incompatible eval).
    txc_keys = canonical_train_keys(
        component=COMPONENT,
        archs=C4_TXC_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000),
    )
    tsae_keys = canonical_train_keys(
        component=COMPONENT,
        archs=C4_TSAE_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=2),
    )
    topk_keys = canonical_train_keys(
        component=COMPONENT,
        archs=C4_TOPK_ARCHS,
        seeds=HEADLINE_SEEDS,
        datasource_names=(DATASOURCE_NAME,),
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=1),
    )
    # T-sweep cells (decisions § 17): txc_base × {T=10, T=20}.
    txc_T_keys: set[str] = set()
    from temp_bench.config import (
        compute_act_cache_key, compute_train_key, load_arch, load_datasource,
    )
    ack = compute_act_cache_key(load_datasource(DATASOURCE_NAME))
    txc_base_spec = load_arch("txc_base", component=COMPONENT)
    for T in (10, 20):
        merged = {**txc_base_spec.hparams, "T": T}
        spec = txc_base_spec.model_copy(update={"hparams": merged})
        for seed in HEADLINE_SEEDS:
            txc_T_keys.add(compute_train_key(
                arch=spec, seed=seed,
                training_cfg=TrainingConfig(
                    n_steps=20_000, arch_hparams_override={"T": T},
                ),
                act_cache_key=ack,
            ))
    valid_keys = txc_keys | tsae_keys | topk_keys | txc_T_keys

    real_rows = [
        r for r in rows
        if not r.eval_cfg.get("smoke", False)
        and int(r.eval_cfg.get("n_features", 256)) >= 256
        and r.train_key in valid_keys
    ]

    if not real_rows:
        n_other = len(rows)
        return AnalysisResult(
            markdown=_placeholder_markdown(
                f"no real BASE cells yet ({n_other} other row(s) filtered)."
            ),
            results={"n_other_rows": n_other},
            plot_paths=[],
        )

    # Group by arch
    grouped: dict[str, list[dict]] = defaultdict(list)
    for r in real_rows:
        sem = r.metrics.get("top_N_semantic")
        n_judged = r.metrics.get("n_features_judged")
        if sem is None or n_judged is None:
            continue
        grouped[r.arch].append({
            "seed": r.seed,
            "top_N_semantic": int(sem),
            "n_features_judged": int(n_judged),
            "judge_agreement": float(r.metrics.get("judge_agreement", 0.0)),
        })

    summary: dict[str, dict] = {}
    for arch in HEADLINE_ARCHS:
        cells = grouped.get(arch, [])
        if not cells:
            continue
        sems = [c["top_N_semantic"] for c in cells]
        agrs = [c["judge_agreement"] for c in cells]
        n_judged = max(c["n_features_judged"] for c in cells)
        summary[arch] = {
            "n_seeds": len(cells),
            "seeds": sorted({c["seed"] for c in cells}),
            "mean_top_N_semantic": float(mean(sems)),
            "std_seeds_top_N_semantic": float(stdev(sems)) if len(sems) > 1 else 0.0,
            "mean_judge_agreement": float(mean(agrs)),
            "n_features_judged": n_judged,
        }

    # ── Pareto plot: y = top_N_semantic, x = C3 mean_auc at k=20
    c3 = _build_c3_mean_auc_lookup()
    PLOT_DIR.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(7, 5))
    colour_map = {
        "topk_sae": "tab:blue",
        "tsae_paper": "tab:orange",
        "txc_base": "tab:green",
        "txc_pro": "tab:purple",
    }
    have_pareto = False
    for arch, cells in grouped.items():
        xs, ys = [], []
        for c in cells:
            x = c3.get((arch, c["seed"], 20))
            if x is None:
                continue
            xs.append(x); ys.append(c["top_N_semantic"])
        if not xs:
            continue
        ax.scatter(xs, ys, color=colour_map.get(arch, "tab:gray"),
                   label=arch, s=64, edgecolor="black", linewidth=0.5)
        have_pareto = True
    if have_pareto:
        ax.set_xlabel("C3 mean AUC at k=20 (BASE)")
        ax.set_ylabel("C4 top-256 SEMANTIC count")
        ax.set_title(
            f"C4 BASE — Pareto: qualitative vs probing\n"
            f"subject = google/gemma-2-2b (NOT -it)",
            fontsize=10,
        )
        ax.legend(loc="best", fontsize=9)
        ax.grid(alpha=0.3)
    plot_path = PLOT_DIR / "pareto_base.png"
    save_figure(fig, plot_path)
    plt.close(fig)

    # Markdown
    md_lines = [
        "_(Auto-generated by `experiments/c4_qualitative_base/analysis.py` — "
        "do not hand-edit. Mirrors `experiments/c4_qualitative/` arch-for-arch "
        "with the BASE Gemma datasource. agent_paper integrates IT + BASE at "
        "paper-render time.)_",
        "",
        f"Subject: `google/gemma-2-2b` (BASE, NOT `-it`). Layer 13.",
        f"Concat corpora: concat_A + concat_B + concat_random. "
        f"N=256 top-features judged by Anthropic Haiku.",
        f"Seeds: {list(HEADLINE_SEEDS)}.",
        "",
        "| arch | top_N_SEMANTIC ± σ_seeds | judge agreement | n_seeds |",
        "|---|---:|---:|---:|",
    ]
    for arch in HEADLINE_ARCHS:
        if arch not in summary:
            continue
        s = summary[arch]
        md_lines.append(
            f"| {arch} | {s['mean_top_N_semantic']:.1f} ± {s['std_seeds_top_N_semantic']:.1f} "
            f"| {s['mean_judge_agreement']:.3f} | {s['n_seeds']} |"
        )
    md_lines.append("")
    md_lines.append(
        f"![C4 BASE Pareto](../../experiments/{EXP_DIR.name}/plots/{plot_path.name})"
    )
    md_lines.append("")
    md_lines.append(
        "_TFA is excluded from BASE C4 — its (N, T=5, d_sae) output shape "
        "is incompatible with `qualitative.encode_concat_corpus` (which "
        "expects (N, d_sae)). Same exclusion applies on IT side._"
    )
    md = "\n".join(md_lines) + "\n"

    return AnalysisResult(
        markdown=md,
        results={
            "datasource": DATASOURCE_NAME,
            "subject_model": "google/gemma-2-2b",
            "by_arch": summary,
            "n_real_rows": len(real_rows),
        },
        plot_paths=[plot_path.relative_to(EXP_DIR.parent.parent)],
    )


def main():
    result = run_analysis()
    import json
    out_path = EXP_DIR / "results.json"
    out_path.write_text(json.dumps(result.results, indent=2))
    print(f"[c4_qualitative_base.analysis] wrote {out_path} "
          f"(n_real_rows={result.results.get('n_real_rows', 0)})")
    md_preview = result.markdown[:600] + ("..." if len(result.markdown) > 600 else "")
    print(f"\n--- markdown preview ---\n{md_preview}")


if __name__ == "__main__":
    main()
