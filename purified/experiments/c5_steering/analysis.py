"""C5 — RLHF steering: aggregate seed-mean coh-vs-success curves.

Owned by ``temp_bench.report.render(component="c5")``. Edit this file
to change anything between the AUTO-RESULTS markers in
``docs/components/c5.md``; never hand-edit the markdown
(PROTOCOL.md § 7 *Results live in state*).

The c5.md hypothesis: TXC-base + TXC-pro produce coh-vs-success curves
**comparable to** T-SAE; both match T-SAE at high coherence (coh ≥
1.75). Headline for the paper table: ``success_at_coh_1.75`` (3-seed
mean ± stderr) per arch.
"""

from __future__ import annotations

import math
from collections import defaultdict
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt

from temp_bench.plotting import save_figure
from temp_bench.report import AnalysisResult, canonical_train_keys, query_leaderboard


COMPONENT = "c5"
EXP_DIR = Path(__file__).parent
PLOT_DIR = EXP_DIR / "plots"

# C5 sweep canonicalization. Used by ``run_analysis`` to filter
# leaderboard rows down to "only cells trained under the current
# canonical TrainingConfig defaults" (decisions.md § 12 mandates a
# uniform batch=1024 / n_steps=25k schedule across all archs and
# components — pre-2026-05-04 cells stay in the leaderboard for diff
# but must NOT mix into the AUTO-RESULTS table). The helper computes
# train_keys from current TrainingConfig() defaults; when paper-wide
# defaults change, this filter automatically tracks them.
ARCHS = ("tsae_paper", "txc_base", "txc_pro")
SEEDS = (1, 2, 42)
DATASOURCE_NAMES = ("gemma_2_2b_it_l13_fineweb_24k128",)


def _placeholder(reason: str) -> str:
    return (
        "_(Auto-generated by `experiments/c5_steering/analysis.py` — "
        "do not hand-edit between AUTO-RESULTS markers.)_\n\n"
        f"No results yet: {reason}\n\n"
        "Expected pattern once the steering sweep lands:\n\n"
        "- T-SAE peak unconstrained (~1.80) beats TXC peak unconstrained, "
        "but at coh ≥ 1.75 the curves cross and TXC matches.\n"
        "- Honest report: no architecture clearly dominates; TXC matches T-SAE.\n"
    )


def _stderr(values: list[float]) -> float:
    n = len(values)
    if n < 2:
        return float("nan")
    mean = sum(values) / n
    var = sum((v - mean) ** 2 for v in values) / (n - 1)
    return math.sqrt(var / n)


def _aggregate(
    rows: list[Any],
) -> tuple[
    dict[str, dict[str, list[float]]],     # by arch -> metric_key -> [seed_vals]
    dict[str, set[int]],                   # by arch -> seeds
]:
    """Group leaderboard rows by ``arch`` → ``metric_key`` → ``[seed_value]``.

    Each row's ``metrics`` dict is the flat output of
    :func:`temp_bench.case_studies.steering.flatten_metrics`. We keep
    every key starting with ``success_at_coh_`` (binary fraction;
    legacy headline) or ``peak_success_grade_at_coh_`` (continuous
    0-3 mean, peaked over strengths; new headline matching wasteland
    phase-7 ``peak15``/``peak175`` convention) plus ``mean_coh`` /
    ``mean_success``.
    """
    by_arch: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    seeds_by_arch: dict[str, set[int]] = defaultdict(set)
    keep_keys = {"mean_coh", "mean_success"}
    for r in rows:
        m = r.metrics
        seeds_by_arch[r.arch].add(r.seed)
        for k, v in m.items():
            if (
                k.startswith("success_at_coh_")
                or k.startswith("peak_success_grade_at_coh_")
                or k in keep_keys
            ):
                by_arch[r.arch][k].append(float(v))
    return dict(by_arch), dict(seeds_by_arch)


def _plot_coh_threshold_curves(
    by_arch: dict[str, dict[str, list[float]]],
    coh_thresholds: list[float],
    out_path: Path,
    *,
    metric_prefix: str = "success_at_coh_",
    ylabel: str = "success rate (success ≥ 2 | coh ≥ τ)",
    title: str = "C5 — coh-vs-success (binary fraction; 3-seed mean ± stderr)",
) -> None:
    fig, ax = plt.subplots(figsize=(6, 4))
    for arch, metric_lists in sorted(by_arch.items()):
        means = []
        errs = []
        for tau in coh_thresholds:
            key = f"{metric_prefix}{tau:g}"
            vals = metric_lists.get(key, [])
            means.append(sum(vals) / len(vals) if vals else float("nan"))
            errs.append(_stderr(vals))
        ax.errorbar(
            coh_thresholds, means, yerr=errs,
            marker="o", capsize=3, label=arch,
        )
    ax.set_xlabel("coherence threshold τ")
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.legend()
    ax.grid(alpha=0.3)
    save_figure(fig, out_path)


def run_analysis() -> AnalysisResult:
    all_rows = query_leaderboard(component=COMPONENT)
    # Skip smoke-test cells (matches agent_nlp's c3 convention).
    rows = [r for r in all_rows if not r.eval_cfg.get("smoke")]
    # Filter to canonical train_keys only (decisions.md § 12 — exclude
    # pre-2026-05-04 batch=256 cells from the rendered AUTO-RESULTS
    # while keeping them in leaderboard.jsonl for diff comparison).
    valid_train_keys = canonical_train_keys(
        component=COMPONENT,
        archs=ARCHS,
        seeds=SEEDS,
        datasource_names=DATASOURCE_NAMES,
    )
    rows = [r for r in rows if r.train_key in valid_train_keys]
    if not rows:
        return AnalysisResult(
            markdown=_placeholder(
                "no canonical-config cells run yet — see "
                "experiments/c5_steering/run.py (TrainingConfig defaults: "
                "batch=1024, n_steps=25_000, plateau_off per decisions.md § 12)"
            ),
            results={},
            plot_paths=[],
        )

    by_arch, seeds_by_arch = _aggregate(rows)

    # Discover the actual coh-threshold grid from metric keys (defensive
    # — if someone runs with a non-default grid, plot what's there).
    seen_taus: set[float] = set()
    for metrics in by_arch.values():
        for k in metrics:
            if k.startswith("success_at_coh_"):
                tau_str = k[len("success_at_coh_"):]
                try:
                    seen_taus.add(float(tau_str))
                except ValueError:
                    pass
    coh_thresholds = sorted(seen_taus)
    if not coh_thresholds:
        return AnalysisResult(
            markdown=_placeholder("rows present but no success_at_coh_* metrics found"),
            results={},
            plot_paths=[],
        )

    # Detect whether the new continuous-grade metric is present in
    # any leaderboard row. It's only emitted by cells run after
    # 2026-05-04 OR backfilled via reaggregate_from_judge_outputs.
    has_peak_grade = any(
        any(k.startswith("peak_success_grade_at_coh_") for k in metrics)
        for metrics in by_arch.values()
    )

    PLOT_DIR.mkdir(parents=True, exist_ok=True)
    plots: list[Path] = []

    fraction_plot = PLOT_DIR / "c5_coh_success_curves.png"
    _plot_coh_threshold_curves(
        by_arch, coh_thresholds, fraction_plot,
        metric_prefix="success_at_coh_",
        ylabel="success rate (success ≥ 2 | coh ≥ τ)",
        title="C5 — coh-vs-success (binary fraction; 3-seed mean ± stderr)",
    )
    plots.append(fraction_plot)

    if has_peak_grade:
        peak_plot = PLOT_DIR / "c5_peak_success_grade_curves.png"
        _plot_coh_threshold_curves(
            by_arch, coh_thresholds, peak_plot,
            metric_prefix="peak_success_grade_at_coh_",
            ylabel="peak mean success grade (max-strength | coh ≥ τ)",
            title="C5 — peak success grade (0-3 scale; wasteland-comparable)",
        )
        plots.append(peak_plot)

    def _ms(vs: list[float]) -> str:
        if not vs:
            return "—"
        m = sum(vs) / len(vs)
        e = _stderr(vs)
        if math.isnan(e):
            return f"{m:.3f}"
        return f"{m:.3f} ± {e:.3f}"

    md_lines: list[str] = [
        "_(Auto-generated by `experiments/c5_steering/analysis.py` — "
        "do not hand-edit between AUTO-RESULTS markers.)_\n",
        f"### Steering — coh-vs-success ({len(rows)} cells, "
        f"{len(by_arch)} archs, "
        f"{sum(len(s) for s in seeds_by_arch.values())} arch-seed pairs)\n",
    ]

    if has_peak_grade:
        md_lines += [
            "**Headline — peak success grade at coh ≥ τ** "
            "(0-3 scale; max-over-strengths of mean success_grade conditioned "
            "on coh_grade ≥ τ; wasteland phase-7 convention):\n",
            "| arch | n seeds | peak grade @ coh ≥ 1.5 | peak grade @ coh ≥ 1.75 | peak grade @ coh ≥ 2.0 | mean coh | mean success |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        for arch in sorted(by_arch):
            m = by_arch[arch]
            md_lines.append(
                f"| {arch} | {len(seeds_by_arch[arch])} | "
                f"{_ms(m.get('peak_success_grade_at_coh_1.5', []))} | "
                f"{_ms(m.get('peak_success_grade_at_coh_1.75', []))} | "
                f"{_ms(m.get('peak_success_grade_at_coh_2', []))} | "
                f"{_ms(m.get('mean_coh', []))} | "
                f"{_ms(m.get('mean_success', []))} |"
            )
        md_lines.append("")
        md_lines.append(
            f"![peak success grade curves](../../experiments/c5_steering/plots/"
            f"{peak_plot.name})"
        )
        md_lines.append("")
        md_lines.append("---\n")
        md_lines.append(
            "**Supplementary — binary fraction at coh ≥ τ** "
            "(success_grade ≥ 2 AND coh_grade ≥ τ; T-SAE paper Table 2 'green cell' convention; "
            "low dynamic range because both threshold events almost always co-occur):\n"
        )
    else:
        md_lines.append(
            "**Headline — binary fraction at coh ≥ τ** "
            "(success_grade ≥ 2 AND coh_grade ≥ τ; T-SAE paper Table 2 convention):\n"
        )
        md_lines.append(
            "_⚠ The wasteland-comparable continuous-grade metric "
            "(`peak_success_grade_at_coh_<τ>`) is not yet present in any "
            "leaderboard row. To backfill existing cells without re-judging, "
            "run `temp_bench.case_studies.steering.reaggregate_from_judge_outputs("
            "<eval_key>/judge_outputs.jsonl)` per cell — see agent_steer's "
            "open question + briefing._\n"
        )

    md_lines += [
        "| arch | n seeds | success @ coh ≥ 1.75 | success @ coh ≥ 2.0 | mean coh | mean success |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    results: dict[str, Any] = {"thresholds": coh_thresholds, "by_arch": {}}
    for arch in sorted(by_arch):
        metrics = by_arch[arch]
        n_seeds = len(seeds_by_arch[arch])
        md_lines.append(
            f"| {arch} | {n_seeds} | "
            f"{_ms(metrics.get('success_at_coh_1.75', []))} | "
            f"{_ms(metrics.get('success_at_coh_2', []))} | "
            f"{_ms(metrics.get('mean_coh', []))} | "
            f"{_ms(metrics.get('mean_success', []))} |"
        )
        arch_summary: dict[str, Any] = {"n_seeds": n_seeds}
        for k, v in metrics.items():
            arch_summary[f"mean_{k}"] = sum(v) / len(v) if v else float("nan")
            arch_summary[f"stderr_{k}"] = _stderr(v)
        results["by_arch"][arch] = arch_summary

    md_lines.append("")
    md_lines.append(
        f"![coh-vs-success (binary fraction)](../../experiments/c5_steering/plots/"
        f"{fraction_plot.name})"
    )

    return AnalysisResult(
        markdown="\n".join(md_lines) + "\n",
        results=results,
        plot_paths=plots,
    )


if __name__ == "__main__":
    out = run_analysis()
    print(out.markdown)
