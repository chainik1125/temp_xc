# C5 sweep canonicalization. Used by ``run_analysis`` to filter
# leaderboard rows down to "only cells trained under the current
# canonical TrainingConfig defaults" (decisions.md § 12 mandates a
# uniform batch=1024 / n_steps=25k schedule across all archs and
# components — pre-2026-05-04 cells stay in the leaderboard for diff
# but must NOT mix into the AUTO-RESULTS table). The helper computes
# train_keys from current TrainingConfig() defaults; when paper-wide
# defaults change, this filter automatically tracks them.
ARCHS = ("tsae_paper", "txc_base", "txc_pro")
SEEDS = (1, 2, 42)
DATASOURCE_NAMES = ("gemma_2_2b_it_l13_fineweb_24k128",)
# Pre-2026-05-05 v1.0.0 cells used raw-activation argmax for feature
# selection (a bug — picked the same always-on feature for ~all 30
# concepts, giving 0.13 mean success_grade vs the wasteland's 1.13
# anchor). v1.1.0 fixes this with concept-lift selection. Old 1.0.0
# rows stay in leaderboard.jsonl for diff; AUTO-RESULTS reads only
# 1.1.0.
HEADLINE_EVAL_PROTOCOL_VERSION = "1.1.0"


def _placeholder(reason: str) -> str:
    return (
        "_(Auto-generated by `experiments/c5_steering/analysis.py` — "
        "do not hand-edit between AUTO-RESULTS markers.)_\n\n"
        f"No results yet: {reason}\n\n"
        "Expected pattern once the steering sweep lands:\n\n"
        "- T-SAE peak unconstrained (~1.80) beats TXC peak unconstrained, "
        "but at coh ≥ 1.75 the curves cross and TXC matches.\n"
        "- Honest report: no architecture clearly dominates; TXC matches T-SAE.\n"
    )


def _stderr(values: list[float]) -> float:
    n = len(values)
    if n < 2:
        return float("nan")
    mean = sum(values) / n
    var = sum((v - mean) ** 2 for v in values) / (n - 1)
    return math.sqrt(var / n)


def _aggregate(
    rows: list[Any],
) -> tuple[
    dict[str, dict[str, list[float]]],     # by arch -> metric_key -> [seed_vals]
    dict[str, set[int]],                   # by arch -> seeds
]:
    """Group leaderboard rows by ``arch`` → ``metric_key`` → ``[seed_value]``.

    Each row's ``metrics`` dict is the flat output of
    :func:`temp_bench.case_studies.steering.flatten_metrics`. We keep
    every key starting with ``success_at_coh_`` (binary fraction;
    legacy headline) or ``peak_success_grade_at_coh_`` (continuous
    0-3 mean, peaked over strengths; new headline matching wasteland
    phase-7 ``peak15``/``peak175`` convention) plus ``mean_coh`` /
    ``mean_success``.
    """
    by_arch: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    seeds_by_arch: dict[str, set[int]] = defaultdict(set)
    keep_keys = {"mean_coh", "mean_success"}
    for r in rows:
        m = r.metrics
        seeds_by_arch[r.arch].add(r.seed)
        for k, v in m.items():
            if (
                k.startswith("success_at_coh_")
                or k.startswith("peak_success_grade_at_coh_")
                or k in keep_keys
            ):
                by_arch[r.arch][k].append(float(v))
    return dict(by_arch), dict(seeds_by_arch)


def _per_strength_means(eval_keys: list[str]) -> dict[float, dict[str, float]] | None:
    """Read ``grades.jsonl`` for each cell, average across (seed × concept)
    per strength. Returns ``{strength: {"mean_coh", "mean_succ", "n"}}``
    or ``None`` if no run_dir is available.

    Falls back to ``judge_outputs.jsonl`` (per-call rows with
    ``head`` ∈ {success, coherence}, ``label`` ∈ 0-3) when
    ``grades.jsonl`` is absent — agent_filler's driver only persisted
    judge_outputs.jsonl + metrics.json (no grades.jsonl), so my Pareto
    helper has to reconstruct the per-(strength, idx) (success, coherence)
    pairs from the per-call judge output.

    This drives the wasteland-style Pareto plot — a parametric curve
    over strength where each point is ``(mean_coh(s), mean_succ(s))``
    averaged over all seeds × concepts at that strength. Strength
    increases trace the curve from "weak steering, high coh" through
    a knee to "over-steered, coh collapses".
    """
    by_s_succ: dict[float, list[float]] = defaultdict(list)
    by_s_coh: dict[float, list[float]] = defaultdict(list)
    for ek in eval_keys:
        rd = run_dir(ek)
        grades_path = rd / "grades.jsonl"
        judge_path = rd / "judge_outputs.jsonl"
        if grades_path.exists():
            for line in grades_path.open():
                line = line.strip()
                if not line:
                    continue
                r = json.loads(line)
                s_g = r.get("success_grade")
                c_g = r.get("coherence_grade")
                if s_g is None or c_g is None:
                    continue
                s = float(r["strength"])
                by_s_succ[s].append(float(s_g))
                by_s_coh[s].append(float(c_g))
        elif judge_path.exists():
            # Reconstruct from per-call judge outputs. Each (idx, head)
            # is a separate row; pair them into (success_grade,
            # coherence_grade) by idx within the same strength.
            by_idx: dict[int, dict[str, Any]] = defaultdict(dict)
            for line in judge_path.open():
                line = line.strip()
                if not line:
                    continue
                r = json.loads(line)
                if r.get("label") is None:
                    continue
                head = r.get("head")
                if head not in ("success", "coherence"):
                    continue
                idx = int(r["idx"])
                by_idx[idx][head] = float(r["label"])
                by_idx[idx]["strength"] = float(r["strength"])
            for rec in by_idx.values():
                if "success" in rec and "coherence" in rec:
                    s = rec["strength"]
                    by_s_succ[s].append(rec["success"])
                    by_s_coh[s].append(rec["coherence"])
    if not by_s_succ:
        return None
    return {
        s: {
            "mean_coh": float(np.mean(by_s_coh[s])),
            "mean_succ": float(np.mean(by_s_succ[s])),
            "n": len(by_s_succ[s]),
        }
        for s in sorted(by_s_succ)
    }


def _plot_pareto(
    eval_keys_by_arch: dict[str, list[str]],
    out_path: Path,
) -> Path | None:
    """Wasteland-style Pareto frontier: parametric curve over strength,
    one line per arch. x = mean coherence at that strength (averaged
    over all seeds × concepts), y = mean success grade likewise.
    Annotates the cliff15 = ``max success at coh ≥ 1.5`` with a star.

    Source convention:
    ``origin/han-phase7-unification:experiments/phase7_unification/case_studies/steering/plot_focused_pareto.py``.
    """
    fig, ax = plt.subplots(figsize=(7, 5))
    plotted = False
    for arch in sorted(eval_keys_by_arch):
        per_s = _per_strength_means(eval_keys_by_arch[arch])
        if per_s is None:
            continue
        plotted = True
        s_arr = sorted(per_s)
        coh = [per_s[s]["mean_coh"] for s in s_arr]
        succ = [per_s[s]["mean_succ"] for s in s_arr]
        ax.plot(
            coh, succ, marker="o", lw=2.0, markersize=6,
            label=f"{arch} (n_seeds={len(eval_keys_by_arch[arch])})",
        )
        # cliff15 star: peak success at coh ≥ 1.5
        valid_15 = [(s, c, su) for s, c, su in zip(s_arr, coh, succ) if c >= 1.5]
        if valid_15:
            peak = max(valid_15, key=lambda x: x[2])
            ax.plot(peak[1], peak[2], "*", markersize=18,
                    markeredgecolor="black", markeredgewidth=1.0, zorder=10)
    if not plotted:
        plt.close(fig)
        return None
    ax.axvline(1.5, color="grey", linestyle=":", alpha=0.6)
    ax.text(1.51, 0.05, "coh=1.5 (prereg)", fontsize=9, color="grey")
    ax.set_xlim(0.6, 3.1)
    ax.set_ylim(0.0, 2.6)
    ax.set_xlabel("mean coherence (Sonnet 4.6, 0-3)")
    ax.set_ylabel("mean success grade (Sonnet 4.6, 0-3)")
    ax.set_title(
        "C5 — Pareto frontier: success vs coherence per strength\n"
        "(stars mark peak success at coh ≥ 1.5; wasteland phase-7 convention)"
    )
    ax.legend(loc="upper left", framealpha=0.95)
    ax.grid(alpha=0.3)
    save_figure(fig, out_path)
    return out_path


def run_analysis() -> AnalysisResult:
    all_rows = query_leaderboard(component=COMPONENT)
    # Skip smoke-test cells (matches agent_nlp's c3 convention).
    rows = [r for r in all_rows if not r.eval_cfg.get("smoke")]
    # Filter to canonical train_keys only (decisions.md § 12 — exclude
    # pre-2026-05-04 batch=256 cells from the rendered AUTO-RESULTS
    # while keeping them in leaderboard.jsonl for diff comparison).
    #
    # decisions.md § 15 (2026-05-05 PM): TXC archs and T-SAE now use
    # DIFFERENT canonical training_cfgs:
    #   - TXC archs: n_steps=20_000 (Gemma deadline override)
    #   - T-SAE: n_steps=20_000 + train_window_size=2 (Bhalla/Ye 2025
    #     §3.1 paper-faithful adjacent-pair training; brings per-token
    #     T-SAE from 131K tokens/step down to ~2K, matching SAEBench
    #     canonical scale).
    # Compute both canonical sets and union them. Old v1.1.0 T-SAE rows
    # without train_window_size stay in leaderboard.jsonl for diff but
    # drop out of AUTO-RESULTS once agent_filler's T=2 re-train lands.
    from temp_bench.schemas import TrainingConfig
    txc_train_keys = canonical_train_keys(
        component=COMPONENT,
        archs=("txc_base", "txc_pro"),
        seeds=SEEDS,
        datasource_names=DATASOURCE_NAMES,
        training_cfg=TrainingConfig(n_steps=20_000),
    )
    tsae_train_keys = canonical_train_keys(
        component=COMPONENT,
        archs=("tsae_paper",),
        seeds=SEEDS,
        datasource_names=DATASOURCE_NAMES,
        training_cfg=TrainingConfig(n_steps=20_000, train_window_size=2),
    )
    valid_train_keys = txc_train_keys | tsae_train_keys
    rows = [
        r for r in rows
        if r.train_key in valid_train_keys
        and r.eval_protocol_version == HEADLINE_EVAL_PROTOCOL_VERSION
    ]
    if not rows:
        return AnalysisResult(
            markdown=_placeholder(
                "no canonical-config cells run yet — see "
                "experiments/c5_steering/run.py (TrainingConfig: "
                "batch=1024, n_steps=20_000 [Gemma deadline override], "
                "plateau_off per decisions.md § 12)"
            ),
            results={},
            plot_paths=[],
        )

    by_arch, seeds_by_arch = _aggregate(rows)

    # Discover the actual coh-threshold grid from metric keys (defensive
    # — if someone runs with a non-default grid, plot what's there).
    seen_taus: set[float] = set()
    for metrics in by_arch.values():
        for k in metrics:
            if k.startswith("success_at_coh_"):
                tau_str = k[len("success_at_coh_"):]
                try:
                    seen_taus.add(float(tau_str))
                except ValueError:
                    pass
    coh_thresholds = sorted(seen_taus)
    if not coh_thresholds:
        return AnalysisResult(
            markdown=_placeholder("rows present but no success_at_coh_* metrics found"),
            results={},
            plot_paths=[],
        )

    # Detect whether the new continuous-grade metric is present in
    # any leaderboard row. It's only emitted by cells run after
    # 2026-05-04 OR backfilled via reaggregate_from_judge_outputs.
    has_peak_grade = any(
        any(k.startswith("peak_success_grade_at_coh_") for k in metrics)
        for metrics in by_arch.values()
    )

    PLOT_DIR.mkdir(parents=True, exist_ok=True)
    plots: list[Path] = []

    # Wasteland-style Pareto frontier: parametric over strength, x=coh,
    # y=success. Each line traces an arch's strength sweep — high-strength
    # points collapse coherence, low-strength points have weak success,
    # and a knee somewhere in between marks the cliff15 (star). This is
    # the only headline plot — earlier coh-threshold-curve plots
    # (peak_grade vs τ, success_at_coh vs τ) compressed the data into
    # 1D lines that hid the actual frontier shape.
    pareto_plot = PLOT_DIR / "c5_pareto_frontier.png"
    eval_keys_by_arch: dict[str, list[str]] = defaultdict(list)
    for r in rows:
        eval_keys_by_arch[r.arch].append(r.eval_key)
    if _plot_pareto(eval_keys_by_arch, pareto_plot) is not None:
        plots.append(pareto_plot)

    def _ms(vs: list[float]) -> str:
        if not vs:
            return "—"
        m = sum(vs) / len(vs)
        e = _stderr(vs)
        if math.isnan(e):
            return f"{m:.3f}"
        return f"{m:.3f} ± {e:.3f}"

    md_lines: list[str] = [
        "_(Auto-generated by `experiments/c5_steering/analysis.py` — "
        "do not hand-edit between AUTO-RESULTS markers.)_\n",
        f"### Steering — coh-vs-success ({len(rows)} cells, "
        f"{len(by_arch)} archs, "
        f"{sum(len(s) for s in seeds_by_arch.values())} arch-seed pairs)\n",
    ]

    md_lines += [
        "**Peak success grade at coh ≥ τ** "
        "(0-3 scale; max-over-strengths of mean success_grade conditioned "
        "on coh_grade ≥ τ; wasteland phase-7 convention):\n",
        "| arch | n seeds | peak grade @ coh ≥ 1.5 | peak grade @ coh ≥ 1.75 | peak grade @ coh ≥ 2.0 | mean coh | mean success |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    if not has_peak_grade:
        md_lines.append(
            "_⚠ `peak_success_grade_at_coh_<τ>` not present in any "
            "leaderboard row — table will show '—'. Backfill via "
            "`temp_bench.case_studies.steering.reaggregate_from_judge_outputs(...)` "
            "per cell._"
        )
    results: dict[str, Any] = {"thresholds": coh_thresholds, "by_arch": {}}
    for arch in sorted(by_arch):
        m = by_arch[arch]
        n_seeds = len(seeds_by_arch[arch])
        md_lines.append(
            f"| {arch} | {n_seeds} | "
            f"{_ms(m.get('peak_success_grade_at_coh_1.5', []))} | "
            f"{_ms(m.get('peak_success_grade_at_coh_1.75', []))} | "
            f"{_ms(m.get('peak_success_grade_at_coh_2', []))} | "
            f"{_ms(m.get('mean_coh', []))} | "
            f"{_ms(m.get('mean_success', []))} |"
        )
        arch_summary: dict[str, Any] = {"n_seeds": n_seeds}
        for k, v in m.items():
            arch_summary[f"mean_{k}"] = sum(v) / len(v) if v else float("nan")
            arch_summary[f"stderr_{k}"] = _stderr(v)
        results["by_arch"][arch] = arch_summary

    md_lines.append("")
    md_lines.append(
        f"![Pareto frontier — success vs coherence per strength]"
        f"(../../experiments/c5_steering/plots/{pareto_plot.name})"
    )

    return AnalysisResult(
        markdown="\n".join(md_lines) + "\n",
        results=results,
        plot_paths=plots,
    )


if __name__ == "__main__":
    out = run_analysis()
    print(out.markdown)
