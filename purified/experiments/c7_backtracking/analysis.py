def _placeholder(reason: str) -> str:
    return (
        "_(Auto-generated by `experiments/c7_backtracking/analysis.py` — "
        "do not hand-edit between AUTO-RESULTS markers (PROTOCOL.md § 7).)_\n\n"
        f"No results yet: {reason}\n\n"
        "Headline check pending: does TXC-pro reproduce ~+1.574 peak Δgc on "
        "the inducement axis under our locked-arch set? "
        "Reference (hill-climbed TXC, wasteland) at "
        "`results/c7_backtracking/aniket_reference/cut25/inducement_summary.csv`.\n"
    )


def _gather_judge_outputs() -> list[dict[str, Any]]:
    """Walk every results/runs/*/judge_outputs.jsonl, collect rows."""
    from temp_bench.config import purified_root
    out: list[dict[str, Any]] = []
    runs_dir = purified_root() / "results" / "runs"
    if not runs_dir.exists():
        return out
    for jp in runs_dir.glob("*/judge_outputs.jsonl"):
        try:
            with jp.open() as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        out.append(json.loads(line))
                    except json.JSONDecodeError:
                        continue
        except Exception:
            continue
    return out


def _delta_gc_table_md(delta_gc: dict[str, Any], arch_order: list[str]) -> str:
    """Render the headline Δgc table (peak + magnitude + stability).

    Rows are ordered by descending peak Δgc within ``arch_order``.
    """
    rows: list[tuple[str, float, float, str]] = []  # (arch, peak, mag, stability)
    for arch in arch_order:
        peak = delta_gc["peak"].get(arch)
        if peak is None:
            continue
        rows.append((arch, peak[1], peak[0], delta_gc["stability"].get(arch, "?")))
    rows.sort(key=lambda r: -r[1])

    txc_pro_peak = next((p for (a, p, _, _) in rows if a == "txc_pro"), None)

    lines = [
        "| arch | stability (Δgc>0 / 24) | peak Δgc | peak mag | peak / TXC-pro |",
        "|---|---|---:|---:|---:|",
    ]
    for arch, peak, mag, stab in rows:
        ratio = (peak / txc_pro_peak) if (txc_pro_peak and txc_pro_peak > 0) else float("nan")
        lines.append(
            f"| {arch} | {stab} | {peak:+.3f} | {mag:+.1f} | {ratio:.2f}× |"
        )
    return "\n".join(lines)


def _pr_auc_table_md(rows, S_grid=DEFAULT_PR_AUC_S_GRID) -> str:
    """Render PR-AUC at S ∈ S_grid, mean ± stderr across seeds."""
    by_arch: dict[str, dict[int, list[float]]] = {}
    for r in rows:
        for S in S_grid:
            v = r.metrics.get(f"pr_auc_S{S}")
            if v is None:
                continue
            by_arch.setdefault(r.arch, {}).setdefault(S, []).append(float(v))
    if not by_arch:
        return "_PR-AUC: no detection cells with this metric yet._"
    header = ["| arch |"] + [f" S={S} |" for S in S_grid]
    sep = ["|---|"] + [f"---:|" for _ in S_grid]
    lines = ["".join(header), "".join(sep)]
    for arch in sorted(by_arch):
        cells = [f"| {arch} |"]
        for S in S_grid:
            xs = by_arch[arch].get(S, [])
            if not xs:
                cells.append(" - |")
            else:
                m = float(np.mean(xs))
                s = float(np.std(xs, ddof=1)) / (len(xs) ** 0.5) if len(xs) > 1 else 0.0
                cells.append(f" {m:.3f}±{s:.3f} |")
        lines.append("".join(cells))
    return "\n".join(lines)


def _plot_delta_gc_per_mag(delta_gc: dict[str, Any], arch_order: list[str], out_path: Path) -> Path:
    """4-panel-style plot collapsed to one: per-arch Δgc curves vs magnitude."""
    fig, ax = plt.subplots(figsize=(7, 4.5))
    for arch in arch_order:
        pts = sorted(
            ((m, d) for (a, m), d in delta_gc["by_arch_mag"].items() if a == arch),
            key=lambda x: x[0],
        )
        if not pts:
            continue
        xs, ys = zip(*pts)
        ax.plot(xs, ys, marker="o", markersize=3, linewidth=1.0, label=arch)
    ax.axhline(0.0, color="black", linewidth=0.5, linestyle="--")
    ax.set_xlabel("steering magnitude (raw)")
    ax.set_ylabel(r"$\Delta_{gc}$ (genuine backtracking events vs mag=0)")
    ax.set_title("C7 inducement — per-arch Δgc curves")
    ax.legend(fontsize=8, loc="best")
    return save_figure(fig, out_path)


def _plot_pr_auc_curves(rows, S_grid, out_path: Path) -> Path:
    by_arch: dict[str, dict[int, list[float]]] = {}
    for r in rows:
        for S in S_grid:
            v = r.metrics.get(f"pr_auc_S{S}")
            if v is None:
                continue
            by_arch.setdefault(r.arch, {}).setdefault(S, []).append(float(v))
    fig, ax = plt.subplots(figsize=(6, 4))
    for arch, by_S in by_arch.items():
        Ss = sorted(by_S)
        means = [float(np.mean(by_S[S])) for S in Ss]
        ax.plot(Ss, means, marker="o", label=arch)
    ax.set_xscale("log", base=2)
    ax.set_xlabel("S (top-S features)")
    ax.set_ylabel("PR-AUC (mean across seeds)")
    ax.set_title("C7 detection — sparse-probe PR-AUC")
    ax.legend(fontsize=8, loc="best")
    return save_figure(fig, out_path)


def run_analysis() -> AnalysisResult:
    PLOT_DIR.mkdir(parents=True, exist_ok=True)
    rows = query_leaderboard(component=COMPONENT)

    # Filter to current-config cells only (Han 2026-05-04 PM, decisions § 12).
    valid_keys = _valid_train_keys()
    rows = [r for r in rows if r.train_key in valid_keys]

    # ── Inducement ────────────────────────────────────────────────────
    judge_rows = _gather_judge_outputs()
    # Also filter judge_outputs.jsonl rows to those produced by current-
    # config cells. Each row in judge_outputs.jsonl has (arch, seed, mag);
    # the cell's eval_key (and train_key) lives in the workspace dirname.
    # We re-filter via the run_dir parent → match against valid_keys.
    from temp_bench.cache import _read_jsonl, leaderboard_path
    from temp_bench.config import purified_root
    valid_eval_keys = {r.eval_key for r in rows}
    runs_dir = purified_root() / "results" / "runs"
    valid_judges: list[dict[str, Any]] = []
    for jp in runs_dir.glob("*/judge_outputs.jsonl") if runs_dir.exists() else []:
        if jp.parent.name not in valid_eval_keys:
            continue
        try:
            with jp.open() as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        valid_judges.append(json.loads(line))
                    except json.JSONDecodeError:
                        continue
        except Exception:
            continue
    judge_rows = valid_judges
    if not judge_rows and not rows:
        return AnalysisResult(
            markdown=_placeholder("no leaderboard rows AND no judge_outputs.jsonl yet"),
            results={},
            plot_paths=[],
        )
    delta_gc = compute_delta_gc(judge_rows) if judge_rows else {
        "by_arch_mag": {}, "stability": {}, "peak": {},
    }
    arch_order = sorted({a for (a, _) in delta_gc["by_arch_mag"]})

    md_parts: list[str] = [
        "_(Auto-generated by `experiments/c7_backtracking/analysis.py` — "
        "do not hand-edit between AUTO-RESULTS markers (PROTOCOL.md § 7).)_\n",
    ]

    if not delta_gc["by_arch_mag"]:
        md_parts.append("**Inducement (Δgc)**: no Sonnet judge calls persisted yet.\n")
    else:
        md_parts.append("### Inducement — Sonnet `genuine_count` (Δgc, baseline-corrected at mag=0)\n")
        md_parts.append(_delta_gc_table_md(delta_gc, arch_order))
        plot_path = _plot_delta_gc_per_mag(
            delta_gc, arch_order, PLOT_DIR / "delta_gc_per_magnitude.png",
        )
        md_parts.append(
            f"\n![Δgc per magnitude](../../experiments/c7_backtracking/plots/{plot_path.name})"
        )

    # ── Detection ─────────────────────────────────────────────────────
    if rows:
        md_parts.append("\n\n### Detection — PR-AUC (sparse probe, GroupKFold by qid)\n")
        md_parts.append(_pr_auc_table_md(rows))
        if any(any(r.metrics.get(f"pr_auc_S{S}") is not None for S in DEFAULT_PR_AUC_S_GRID) for r in rows):
            plot_path = _plot_pr_auc_curves(
                rows, DEFAULT_PR_AUC_S_GRID, PLOT_DIR / "pr_auc_per_S.png",
            )
            md_parts.append(
                f"\n![PR-AUC vs S](../../experiments/c7_backtracking/plots/{plot_path.name})"
            )
    else:
        md_parts.append(
            "\n\n**Detection**: no leaderboard rows yet — eval cells haven't run.\n"
        )

    # ── Headline check ────────────────────────────────────────────────
    txc_pro_peak = delta_gc["peak"].get("txc_pro")
    if txc_pro_peak is not None:
        ref = ANIKET_REFERENCE_PEAK_DELTA_GC.get("txc_h8")  # closest analog
        if ref is not None:
            md_parts.append(
                "\n\n**Headline reproducibility** — TXC-pro peak Δgc = "
                f"**{txc_pro_peak[1]:+.3f}** at mag={txc_pro_peak[0]:+.1f}; "
                f"Aniket's wasteland TXC-H8 (closest analog) = +{ref[0]:.3f} at mag={ref[1]:+.1f}; "
                f"hill-climbed TXC = +1.574 at mag=−12 (reference, NOT a comparable arch).\n"
            )
    elif rows:
        md_parts.append(
            "\n\n**Headline reproducibility**: TXC-pro inducement cell pending. "
            "Reference numbers in `results/c7_backtracking/aniket_reference/cut25/inducement_summary.csv`.\n"
        )

    # ── Coverage report ───────────────────────────────────────────────
    expected_archs = {"topk_sae", "stacked_sae", "tfa", "tsae_paper", "mlc",
                      "txc_base", "txc_pro"}
    have_archs = {r.arch for r in rows}
    missing = sorted(expected_archs - have_archs)
    if missing:
        md_parts.append(
            f"\n\n**Coverage**: missing arches: `{', '.join(missing)}` "
            "(see agent_back briefing OQ #1 — arch ports gated on agent_paper).\n"
        )

    return AnalysisResult(
        markdown="\n".join(md_parts),
        results={
            "delta_gc": {
                arch: {"peak": p[1], "peak_magnitude": p[0],
                       "stability": delta_gc["stability"].get(arch, "?")}
                for arch, p in delta_gc["peak"].items()
            },
            "n_judge_calls": len(judge_rows),
            "n_leaderboard_cells": len(rows),
            "missing_archs": missing,
        },
        plot_paths=sorted(PLOT_DIR.glob("*.png")),
    )


if __name__ == "__main__":
    res = run_analysis()
    print(res.markdown)
    print("---")
    print(json.dumps(res.results, indent=2, default=str))
