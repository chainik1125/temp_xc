"""C7 backtracking — leaderboard.jsonl + judge_outputs.jsonl → c7.md AUTO-RESULTS.

Per PROTOCOL.md § 7 *Results live in state*: the AUTO-RESULTS block of
``docs/components/c7.md`` is rewritten by ``temp_bench.report.render
(component='c7')`` from this script's :class:`AnalysisResult` return.
Hand-typed numbers in the .md between the markers are forbidden.

Two metric axes (mirroring c7.md):

- **Inducement (Δgc)** — primary headline. Computed by
  :func:`temp_bench.case_studies.backtracking.compute_delta_gc` over
  every Sonnet judge call persisted to
  ``results/runs/<eval_key>/judge_outputs.jsonl``. Per-arch peak Δgc
  (with peak magnitude + stability count) goes in the headline table.
- **Detection (PR-AUC)** — per-arch PR-AUC at ``S ∈ {1, 2, 4, 8, 16, 32}``
  read from each cell's leaderboard row's ``metrics["pr_auc_S{S}"]``.

The script is **resilient to a partial sweep** — it will render
"no cells yet" placeholder when leaderboard has no rows for ``c7``,
and it will explicitly call out any missing (arch, seed) combinations.
"""

