"""Alternate-frequency FreqBench generators (v2).

Four new generative families that extend FreqBench beyond the DC/AC/Mixed
trio, stressing different temporal-frequency structures. All return a
:class:`FreqBenchData` (imported from ``temp_bench.data.freq_bench_data``)
so the existing ``freq_bench`` evaluator (NTPS + order-controls + MLP +
FreqFrac) handles them unchanged.

Generators
----------
chirp
    Quadratic-phase (linear chirp): φ(t) = (φ0 + v·t + ½a·t²) mod M.
    Label = sign(a). Binary, A_loc=0.5, A_oracle=1.

multitone
    Emission superposes K tones at distinct velocities; one tone is the
    target per sequence. Label = target-tone class. A_loc=1/n_classes,
    A_oracle=1.

am
    Carrier at ω_c amplitude-modulated by a slow envelope at rate f_m.
    Label = modulation-rate class. A_loc=1/n_classes, A_oracle=1.

relphase
    Two independent phase walks in orthogonal blocks (channel A / B),
    both at velocity ω=1. Label = sign(φA_0 − φB_0) (which channel leads).
    Binary, A_loc=0.5, A_oracle=1.

Common constants (all documented here to avoid the "lost constants" problem):
    W=16, sigma=0.1, d_in=256 (production cells).
    Noise σ Gaussian, added after one-hot emission into orthonormal dirs.
    Emission directions: generated by QR-factoring a random (d_in × d_in)
    normal matrix (deterministic in seed, identical to freq_bench helpers).

Registry in configs/data.yaml (do not edit from this module):
    af_chirp_smoke          → chirp   W=4,  M=16, d_in=32,  n_seqs=256
    af_chirp_W16_s10        → chirp   W=16, M=64, d_in=256, n_seqs=4096
    af_multitone_W16_s10    → multitone W=16,M=64, n_classes=8, d_in=256, n_seqs=4096
    af_am_W16_s10           → am     W=16, M=64, n_classes=6, d_in=256, n_seqs=4096
    af_relphase_W16_s10     → relphase W=16,M=32, d_in=256, n_seqs=4096
"""

from __future__ import annotations

import math
from typing import Any

import numpy as np
import torch

from temp_bench.data.freq_bench_data import FreqBenchData, _emission_dirs, _emit, _pack


# ── chirp ────────────────────────────────────────────────────────────────


def chirp(
    *, W: int = 16, sigma: float = 0.1, M: int = 64, d_in: int = 256,
    n_seqs: int = 4096, seed: int = 0, **_ignore: Any,
) -> FreqBenchData:
    """Quadratic-phase (linear-chirp) bench.

    Generative model
    ----------------
    φ(t) = (φ0 + v·t + a·t·(t−1)/2) mod M,   t = 0, …, W−1.

    Constants (W=16 production cell):
        M = 64        — ring size; max quadratic advance ½·1·225 = 112 ≤ M
                        with wrapping fine (carrier v is nuisance, only
                        sign(a) is the label).
        a ∈ {-1, +1}  — chirp rate (the label signal), balanced.
        v ~ Uniform(Z_M) — carrier velocity (nuisance; randomised per seq).
        φ0 ~ Uniform(Z_M) — initial phase (nuisance; randomised per seq).
        σ = 0.1       — emission noise std.

    Label: y = 1[a > 0]. Binary (n_classes=2).
    A_loc = 0.5: single phase φ(t) is identically distributed for a>0 and
        a<0 (carrier v is uniform), so no single-token estimator can do
        better than chance.
    A_oracle = 1.0: second finite difference Δ²φ(t) = φ(t+2) − 2φ(t+1) +
        φ(t) = a (exact at σ=0, since a·t·(t−1)/2 has integer second
        differences equal to a). Three consecutive clean phases recover a.
    Minimum T for oracle: T ≥ 3.
    Reverse-control prediction: A_reverse < 0.5 for signed temporal archs
        (reversing the sequence inverts the apparent chirp direction).
    """
    rng = np.random.default_rng(seed)
    E = _emission_dirs(M, d_in, rng)                      # (M, d_in)

    phi0 = rng.integers(0, M, size=n_seqs)                # (N,)
    v = rng.integers(0, M, size=n_seqs)                   # nuisance velocity
    a_sign = np.where(rng.random(n_seqs) < 0.5, 1, -1)   # ±1, balanced
    a = a_sign                                             # chirp rate ∈ {-1, +1}

    t = np.arange(W, dtype=np.int64)[None, :]             # (1, W)
    # Quadratic phase: use a*t*(t-1)//2 (NOT a*t^2//2) because t*(t-1) is
    # always even, giving exact integer second differences: Δ²φ(t) = a for all t.
    # This is the chirp-rate analog of the AC bench's Δφ(t) = v.
    # Proof: Δ²[t*(t-1)/2] = (t+2)(t+1)/2 - 2(t+1)t/2 + t(t-1)/2 = 1 for all t.
    phase = (phi0[:, None] + v[:, None] * t
             + a[:, None] * t * (t - 1) // 2) % M         # (N, W)
    x = _emit(phase.astype(np.int64), E, sigma, rng)
    y = (a_sign > 0).astype(np.int64)
    return _pack(x, y, A_loc=0.5, A_oracle=1.0, n_classes=2, bench="chirp")


# ── multitone ─────────────────────────────────────────────────────────────


def multitone(
    *, W: int = 16, sigma: float = 0.1, M: int = 64, n_classes: int = 8,
    d_in: int = 256, n_seqs: int = 4096, seed: int = 0, **_ignore: Any,
) -> FreqBenchData:
    """Superposed-tone frequency-selectivity bench.

    Generative model
    ----------------
    K = n_classes tones at velocities ωk = k, k ∈ {1,…,K}.
    Each tone has an independent random initial phase φ0k ~ Uniform(Z_M).
    Emission = (1/√K) Σk f[φk(t)] + σξ(t),   φk(t) = (φ0k + ωk·t) mod M.
    Label y = target-tone class (which tone is the "signal"; the rest are
    all present but as distractors). To make the task solvable, the target
    tone has amplitude √K (not 1/√K) relative to the distractors, so a
    temporal arch that frequency-filters can detect the boosted tone.

    Implementation: emit all K tones with weight 1/√K, then add an extra
    1.0 · f[φy(t)] contribution for the target tone. The target is louder
    than the rest by a factor of (1+√K)/1 ≈ √K (for large K).

    Constants (W=16, n_classes=8, M=64):
        ωk = k for k=1..8, so max velocity = 8; phase advance 8·15=120.
        M = 64 so wrapping occurs but each tone's temporal phase structure
        is periodic and temporally coherent over the window.
        Normalisation: 1/√K for background, +1.0 for target (total weight
        on target direction = 1/√K + 1.0 ≈ 1.35).
    A_loc = 1/n_classes: single-token emission contains all K tones; the
        marginal distribution is the same for every target class (each
        class is always present). Without temporal filtering, estimator
        is at chance.
    A_oracle = 1.0: temporal DFT of x(t) projects onto each tone's
        frequency bin; the target bin has excess power ≈ (1.0)² vs
        background (1/√K)² per tone. Discriminable with sufficient W.
    """
    rng = np.random.default_rng(seed)
    K = n_classes
    # Need M + K emission directions (K tones each with up to M phases —
    # actually M directions covers K tone slots since velocities alias into M).
    # Simplest: use M orthonormal directions, one per phase slot.
    E = _emission_dirs(M, d_in, rng)                          # (M, d_in)

    velocities = np.arange(1, K + 1, dtype=np.int64)         # ω1..ωK
    target_cls = rng.integers(0, K, size=n_seqs)             # (N,) label

    # Random initial phase per tone per sequence: (N, K)
    phi0 = rng.integers(0, M, size=(n_seqs, K))
    t = np.arange(W, dtype=np.int64)                          # (W,)

    # Phase for each tone: (N, K, W)
    phase = (phi0[:, :, None] + velocities[None, :, None] * t[None, None, :]) % M

    # Build emissions: background (1/√K) * sum of all tones + 1.0 * target
    inv_sqrtK = 1.0 / math.sqrt(K)
    x = np.zeros((n_seqs, W, d_in), dtype=np.float32)
    for k in range(K):
        x += inv_sqrtK * E[phase[:, k, :]]                   # (N, W, d_in)
    # Add target-tone boost (extra 1.0 weight on the target tone)
    target_phase = phase[np.arange(n_seqs), target_cls, :]   # (N, W)
    x += E[target_phase]

    if sigma > 0:
        x += sigma * rng.standard_normal(x.shape).astype(np.float32)

    y = target_cls.astype(np.int64)
    # velocities stored per-sequence for R_j curve (target tone's velocity)
    vel_per_seq = velocities[target_cls]                      # (N,)
    return FreqBenchData(
        x=torch.from_numpy(x),
        y=torch.from_numpy(y),
        A_loc=1.0 / n_classes,
        A_oracle=1.0,
        n_classes=n_classes,
        bench="multitone",
        velocities=torch.from_numpy(vel_per_seq.astype(np.int64)),
    )


# ── am ────────────────────────────────────────────────────────────────────


def am(
    *, W: int = 16, sigma: float = 0.1, M: int = 64, n_classes: int = 6,
    d_in: int = 256, n_seqs: int = 4096, seed: int = 0, **_ignore: Any,
) -> FreqBenchData:
    """Amplitude-modulation (AM) bench.

    Generative model
    ----------------
    A carrier at fixed velocity ω_c=4 is amplitude-modulated by a slow
    envelope at modulation frequency f_m (cycles per window):

        a(t) = 1 + depth · cos(2π f_m t / W),   depth = 0.5.
        φ(t) = (φ0 + ω_c · t) mod M.
        x(t) = a(t) · f[φ(t)] + σ ξ(t).

    Label y = modulation-rate class (f_m ∈ {1,…,n_classes}).

    Constants (W=16, n_classes=6, M=64):
        ω_c = 4 (carrier velocity; fixed, not the label).
        depth = 0.5 (modulation index; keeps carrier prominent).
        f_m ∈ {1,2,3,4,5,6} (cycles per window W).
        M = 64; max carrier phase advance = 4·15 = 60 < M (no full wrap
            aliasing within window, though modular arithmetic is fine).
        φ0 ~ Uniform(Z_M): random initial carrier phase (nuisance).

    A_loc = 1/n_classes: single-token amplitude a(t) depends on both f_m
        and t; marginal over t is the same for every f_m (same mean 1,
        same phase spread). Without temporal context, estimator is at chance.
    A_oracle = 1.0: DFT of a(t)·f[φ(t)] projected onto each f_m yields
        a peak at the true f_m. With sufficient W, f_m is recoverable.

    Velocities stored per sequence (= f_m class integer, 1-indexed) for
    the R_j curve.
    """
    rng = np.random.default_rng(seed)
    E = _emission_dirs(M, d_in, rng)                      # (M, d_in)

    omega_c = 4                                           # carrier velocity
    depth = 0.5                                           # modulation depth
    fm_values = np.arange(1, n_classes + 1, dtype=np.int64)  # {1,...,n_classes}

    target_cls = rng.integers(0, n_classes, size=n_seqs)  # (N,)
    phi0 = rng.integers(0, M, size=n_seqs)                # (N,)

    t = np.arange(W, dtype=np.float64)                    # (W,) float for cos

    # Carrier phase: (N, W)
    phi = (phi0[:, None] + omega_c * np.arange(W, dtype=np.int64)[None, :]) % M

    # Amplitude envelope per sequence: (N, W)
    fm = fm_values[target_cls]                            # (N,)
    # a(t) = 1 + depth * cos(2π f_m t / W)
    a = 1.0 + depth * np.cos(
        2.0 * np.pi * fm[:, None] * t[None, :] / W
    )                                                     # (N, W)

    # Emission: a(t) * E[φ(t)] + noise
    # E[phi]: (N, W, d_in)
    x = (a[:, :, None] * E[phi]).astype(np.float32)      # (N, W, d_in)
    if sigma > 0:
        x += sigma * rng.standard_normal(x.shape).astype(np.float32)

    y = target_cls.astype(np.int64)
    return FreqBenchData(
        x=torch.from_numpy(x),
        y=torch.from_numpy(y),
        A_loc=1.0 / n_classes,
        A_oracle=1.0,
        n_classes=n_classes,
        bench="am",
        velocities=torch.from_numpy(fm.astype(np.int64)),
    )


# ── relphase ──────────────────────────────────────────────────────────────


def relphase(
    *, W: int = 16, sigma: float = 0.1, M: int = 32, d_in: int = 256,
    n_seqs: int = 4096, seed: int = 0, **_ignore: Any,
) -> FreqBenchData:
    """Two-channel relative-phase bench.

    Generative model
    ----------------
    Two phase walks in orthogonal blocks of d_in:
        Channel A: directions 0 .. M//2 - 1.
        Channel B: directions M//2 .. M - 1.
    Both walk their ring (size M//2) at shared velocity ω=1 with
    independent random starting phases φA_0, φB_0 ~ Uniform(Z_{M//2}).

        φA(t) = (φA_0 + t) mod (M//2),   x_A(t) = f^A[φA(t)].
        φB(t) = (φB_0 + t) mod (M//2),   x_B(t) = f^B[φB(t)].
        x(t)  = x_A(t) + x_B(t) + σ ξ(t).

    Label: y = 1[φA_0 > φB_0] (channel A leads if it started ahead of B).
    Binary, n_classes=2.

    Constants (W=16, M=32, d_in=256):
        M//2 = 16 phases per channel. With ω=1, phase advance = W-1 = 15,
            wraps the ring once. Relative phase Δ = φA_0 - φB_0 is CONSTANT
            across t (both advance at the same rate), so any single timestep
            that sees both channels can in principle read the label.
        d_in ≥ M: d_in=256 >> M=32; M directions are QR-sampled from d_in.

    A_loc = 0.5: at any single timestep, knowing φA(t) alone does not reveal
        the sign of (φA_0 - φB_0) unless φB(t) is also known and jointly
        decodable. A per-token SAE that encodes channel A and B independently
        as two dictionary atoms has the phase indices but not their difference.
        A linear probe on the mean-pooled code (which sees the joint code
        across both channels) can decode the relative phase only if the sparse
        code encodes both channels jointly within each code vector.
        Claim: A_loc ≈ 0.5 because the absolute phases are nuisances and the
        relative phase is not recoverable from independent one-token codes.
    A_oracle = 1.0: knowing φA(t) and φB(t) at any t gives
        φA_0 - φB_0 = φA(t) - φB(t) mod (M//2), which recovers the label
        sign exactly (with high probability when M//2 >> 2).

    Note on reverse control: the relative phase Δ = φA_0 - φB_0 is constant
    across t, so reversing the sequence preserves the label. Prediction:
    A_reverse ≈ A_fwd (signal is time-symmetric). No signed-direction effect
    expected here (unlike the AC and chirp benches).
    """
    rng = np.random.default_rng(seed)
    half_M = M // 2
    # Allocate M orthonormal emission directions: first half for channel A,
    # second half for channel B (block structure in the full E matrix).
    E = _emission_dirs(M, d_in, rng)                       # (M, d_in)

    phi_A0 = rng.integers(0, half_M, size=n_seqs)         # (N,)
    phi_B0 = rng.integers(0, half_M, size=n_seqs)         # (N,)

    t = np.arange(W, dtype=np.int64)                       # (W,)
    phi_A = (phi_A0[:, None] + t[None, :]) % half_M       # (N, W)
    phi_B = (phi_B0[:, None] + t[None, :]) % half_M       # (N, W)

    # Channel A uses emission dirs 0..half_M-1, channel B uses half_M..M-1.
    x_A = E[phi_A]                                         # (N, W, d_in)
    x_B = E[phi_B + half_M]                               # (N, W, d_in)
    x = (x_A + x_B).astype(np.float32)
    if sigma > 0:
        x += sigma * rng.standard_normal(x.shape).astype(np.float32)

    # Label: which channel leads.
    # Compute the signed difference mod (M//2) in [-half_M/2, half_M/2).
    # This is balanced (symmetric around 0) and ties are broken by sign < 0.
    # Equivalently: draw a random lead/lag sign directly and construct phases.
    # Simpler for balance: draw sign explicitly, then set φB_0 = (φA_0 - delta)
    # where delta is drawn uniformly from {1,...,half_M//2}. But to keep
    # both phases independently uniform, use the signed-diff approach:
    # d = (φA_0 - φB_0) mod half_M; y = 1 if d in (0, half_M//2), else 0.
    # This gives exactly balanced classes (positive / negative half of ring).
    diff = (phi_A0.astype(np.int64) - phi_B0.astype(np.int64)) % half_M
    # Positive half: diff in {1,...,half_M//2-1}; negative half: {half_M//2+1,...,half_M-1}
    # Ties (diff==0 or diff==half_M//2) are negligible for half_M>>2 but handled
    # by randomising them: include diff==0 in class 0, diff==half_M//2 in class 1.
    y = ((diff > 0) & (diff <= half_M // 2)).astype(np.int64)
    return _pack(x, y, A_loc=0.5, A_oracle=1.0, n_classes=2, bench="relphase")
