"""Direct-sum "which-process" benchmark generator.

J independent generative processes each live in their own orthogonal feature
block of R^{d_in}. A sequence is generated by exactly one "active" process
(whose block emits an AC phase walk) while the other J-1 blocks are
"null" (emit a static DC constant phase repeated for all W tokens). The
activation is the superposition (direct sum) of all J block emissions.

**Key design property — shared emission marginal:**
    - Active block j: phase φ(t) = (φ0 + v_j·t) mod M, |v_j|=1.
      Single-token marginal: Uniform({0,…,M-1}) — ergodic phase walk.
    - Null block j': phase = φ0_j' (constant across time).
      Single-token marginal: Uniform({0,…,M-1}) — random draw at generation.

Both marginals are Uniform(M), so a single-token or order-invariant probe
sees identical distributions from every block and every process.

    A_loc   = 1/J  (single-token probe at chance)
    A_oracle = 1.0  (ordered sequence: active block has changing phases,
                     null blocks have constant phases — identifiable from
                     any two adjacent tokens)

**Label semantics:**
    y ∈ {0, …, J-1} = index of the "active" process (the one with AC
    dynamics). Labels are balanced: exactly n_seqs/J sequences per class.

**Velocity convention:**
    v_j = +1 if j % 2 == 0, else v_j = -1.
    (Two alternating signs; processes further distinguished by block identity.)

**Emission model (per block j of size B = d_in // J):**
    E_j: (M, B) orthonormal emission directions, QR of random (B, B) Gaussian.
    x_j(t) = E_j[phase_j(t)] + σ · ξ_j(t),  ξ ~ N(0, I_B).

**Ring size M = B = d_in // J.**

Constants documented (lost-constants discipline):
    base_speed = 1 (one step per token on Z_M ring)
    rng seeded deterministically from `seed`

Author: Aniket, 2026-06-01.
"""

from __future__ import annotations

import math

import numpy as np
import torch

from temp_bench.data.freq_bench_data import FreqBenchData


# ── helpers ──────────────────────────────────────────────────────────────


def _block_emission_dirs(B: int, rng: np.random.Generator) -> np.ndarray:
    """B orthonormal emission directions in R^B (QR of random Gaussian).

    Returns (B, B) float32 orthogonal matrix; rows are the M=B emission atoms.
    """
    raw = rng.standard_normal((B, B)).astype(np.float32)
    Q, _ = np.linalg.qr(raw)
    return Q                                            # (B, B), rows are atoms


def _block_emissions(
    phases: np.ndarray,          # (N, W) int in [0, M)
    E: np.ndarray,               # (M, B) emission dirs
    sigma: float,
    rng: np.random.Generator,
) -> np.ndarray:
    """Emit phases through E + σ noise → (N, W, B) float32."""
    x = E[phases]                                       # (N, W, B)
    if sigma > 0:
        x = x + sigma * rng.standard_normal(x.shape).astype(np.float32)
    return x.astype(np.float32)


# ── main generator ────────────────────────────────────────────────────────


def which_process(
    *,
    J: int = 4,
    W: int = 16,
    sigma: float = 0.1,
    d_in: int = 256,
    n_seqs: int = 4096,
    seed: int = 0,
    **_ignore,                   # swallow 'bench' key and any other extras
) -> FreqBenchData:
    """Direct-sum which-process benchmark.

    Partitions R^{d_in} into J orthogonal blocks of size B = d_in // J.
    For each sequence exactly one block j (the "active" process) emits an
    AC phase walk; the other J-1 blocks emit a static (DC) constant phase
    repeated for all W tokens.

    Because both the AC and DC marginals are Uniform(M) (see module docstring),
    a per-token or order-invariant probe cannot distinguish active from null
    blocks, so A_loc = 1/J. An order-sensitive probe sees that only block j
    has changing phases, identifying j exactly: A_oracle = 1.0.

    Parameters
    ----------
    J       : int    — number of processes / classes.
    W       : int    — sequence length (== seq_len in the datasource).
    sigma   : float  — Gaussian emission noise std.
    d_in    : int    — total activation dimension (must be divisible by J).
    n_seqs  : int    — number of sequences to materialise.
    seed    : int    — RNG seed (fixes emission dirs + data; deterministic).
    **_ignore         — extra kwargs swallowed (e.g. 'bench' from data.yaml).

    Returns
    -------
    FreqBenchData with:
        x:         (n_seqs, W, d_in)  float32 activations
        y:         (n_seqs,)          long int, values in {0,…,J-1}
        A_loc:     1/J
        A_oracle:  1.0
        n_classes: J
        bench:     "direct_sum"
    """
    if d_in % J != 0:
        raise ValueError(
            f"which_process: d_in ({d_in}) must be divisible by J ({J}). "
            f"Got d_in % J = {d_in % J}."
        )
    if n_seqs % J != 0:
        # Round down to nearest multiple; we'll trim.
        n_seqs_use = (n_seqs // J) * J
    else:
        n_seqs_use = n_seqs

    B = d_in // J          # block size = ring size M
    M = B                   # one phase slot per emission direction
    base_speed = 1          # |v_j| = 1, step one slot per token

    rng = np.random.default_rng(seed)

    # Build one set of emission directions per block.
    # E[j] has shape (M, B) = (B, B) — an orthonormal basis for block j.
    E_blocks = [_block_emission_dirs(B, rng) for _ in range(J)]

    # Assign velocities: +1 for even j, -1 for odd j.
    velocities = np.array(
        [+base_speed if j % 2 == 0 else -base_speed for j in range(J)],
        dtype=np.int64,
    )

    # Balanced labels: n_seqs_use / J sequences per class.
    seqs_per_class = n_seqs_use // J
    y = np.repeat(np.arange(J, dtype=np.int64), seqs_per_class)
    # Shuffle to avoid having all class-0 first (helps probe train/test split).
    rng.shuffle(y)

    # Allocate output.
    x_out = np.zeros((n_seqs_use, W, d_in), dtype=np.float32)

    t = np.arange(W, dtype=np.int64)                   # (W,) time indices

    # For each sequence, emit each block.
    for n in range(n_seqs_use):
        active_j = int(y[n])
        for j in range(J):
            block_start = j * B
            block_end = (j + 1) * B

            if j == active_j:
                # AC block: phase walks at velocity v_j.
                phi0 = int(rng.integers(0, M))
                v = velocities[j]
                phases = (phi0 + v * t) % M             # (W,)
            else:
                # Null (DC) block: constant random phase repeated W times.
                # The single-token marginal is Uniform(M) — same as AC block.
                phi_const = int(rng.integers(0, M))
                phases = np.full(W, phi_const, dtype=np.int64)

            # Emit: look up emission direction for each phase, add noise.
            block_x = E_blocks[j][phases]               # (W, B)
            if sigma > 0:
                block_x = block_x + sigma * rng.standard_normal(
                    (W, B)).astype(np.float32)
            x_out[n, :, block_start:block_end] = block_x

    return FreqBenchData(
        x=torch.from_numpy(x_out),
        y=torch.from_numpy(y),
        A_loc=float(1.0 / J),
        A_oracle=1.0,
        n_classes=J,
        bench="direct_sum",
    )
