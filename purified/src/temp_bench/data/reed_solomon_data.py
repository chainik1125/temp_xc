"""Reed–Solomon temporal-encoding bench — degree-D polynomial phase.

Generalises the FreqBench **AC bench** (a degree-1 phase walk) to a
degree-D polynomial phase trajectory. Grounded in Dmitry's "polynomial
perspective" (see docs/aniket/reed_solomon_plan.md): the AC walk
φ(t)=φ0+v·t is Reed–Solomon at polynomial length 1; sweeping the degree
D∈{1,2,3} is the RS ladder. Higher D needs more timesteps to pin down the
message, so per-token / single-position SAEs degrade while window archs win.

Construction (Newton forward-difference form, exact integers on the ring):

    φ(t) = (Σ_{j=0}^{D} C(t, j) · m_j) mod M,    t = 0, …, W-1,

where the *message* m = (m_0, …, m_D) is the vector of finite-difference
initial conditions: m_0 = φ0 (initial phase), m_1 = initial velocity, …,
m_D = the constant D-th difference (the "leading symbol"). The sequence is
generated by the standard difference-table iteration
``d[k] += d[k+1]`` so all arithmetic is integer mod M.

- D=1 ⇒ φ(t)=m_0+m_1·t — reproduces ``freq_bench_ac`` (m_0=φ0, m_1=v).
- D=2 ⇒ quadratic phase = linear chirp (constant acceleration m_2).
- D=3 ⇒ cubic.

Emission is one-hot(φ(t)) + σ·noise on M orthonormal directions, exactly as
the other FreqBench benches.

Labels / targets (all three are READOUTS on the same trained code — see
``temp_bench.evals.freq_bench``; Q2 resolved "do all three"):

    y          leading-coefficient CLASS index over a symmetric ladder Ω
               (multiclass; the primary A / NTPS).            target (b)
    velocities signed leading coefficient m_D → sign(m_D) gives the binary
               direction target.                              target (a)
    coeffs     the full message m=(m_0,…,m_D) → regression NMSE.  target (c)

Oracle: the D-th finite difference of the (noiseless) observed phase equals
m_D mod M, so A_oracle = 1 and A_loc = 1/|Ω| (a single token reveals a
phase but nothing about the leading coefficient). Finite differencing
commutes with mod M, so ring wrapping does not break the oracle as long as
the ladder elements are distinct mod M (|m_D| < M/2 below).
"""

from __future__ import annotations

import numpy as np
import torch

from temp_bench.data.freq_bench_data import (
    FreqBenchData,
    _emission_dirs,
    _emit,
)


def _leading_ladder(n_classes: int) -> np.ndarray:
    """Symmetric signed ladder Ω for the leading coefficient m_D.

    n_classes even ⇒ Ω = ±{1, …, n_classes/2}; odd ⇒ adds 0 in the middle
    (a degenerate "no leading motion" class). Elements distinct mod M for
    M ≫ n_classes, so the oracle stays exact.
    """
    half = n_classes // 2
    speeds = list(range(1, half + 1))
    omega = [-s for s in speeds] + speeds
    if n_classes % 2 == 1:
        omega = omega[:half] + [0] + omega[half:]
    return np.array(omega, dtype=np.int64)


def rs_poly_phase(
    *, W: int = 16, sigma: float = 0.1, M: int = 64, degree: int = 2,
    n_classes: int = 8, lower_range: int = 3, d_in: int = 256,
    n_seqs: int = 4096, seed: int = 0, **_ignore,
) -> FreqBenchData:
    """Degree-``degree`` polynomial-phase bench (Reed–Solomon ladder).

    The leading finite difference m_D is drawn from a symmetric ladder Ω of
    ``n_classes`` values (the label). Lower-order initial conditions m_0…
    m_{D-1} are nuisance: m_0=φ0~U(0,M), m_k~U(-lower_range, lower_range).
    """
    if degree < 1:
        raise ValueError(f"degree must be ≥ 1 (got {degree})")
    rng = np.random.default_rng(seed)
    E = _emission_dirs(M, d_in, rng)                          # (M, d_in)
    omega = _leading_ladder(n_classes)
    n_classes = len(omega)

    cls = rng.integers(0, n_classes, size=n_seqs)             # label
    m_D = omega[cls].astype(np.int64)                         # leading coeff

    # Message m = (m_0, …, m_D): finite-difference initial conditions.
    m = np.zeros((n_seqs, degree + 1), dtype=np.int64)
    m[:, 0] = rng.integers(0, M, size=n_seqs)                 # φ0
    for k in range(1, degree):
        m[:, k] = rng.integers(-lower_range, lower_range + 1, size=n_seqs)
    m[:, degree] = m_D

    # Difference-table iteration → φ(t) = Σ_j C(t,j) m_j  (degree-D poly).
    d = m.copy()                                              # (N, D+1)
    phase = np.empty((n_seqs, W), dtype=np.int64)
    for t in range(W):
        phase[:, t] = d[:, 0] % M
        for k in range(degree):                               # d[k] += d[k+1]
            d[:, k] = d[:, k] + d[:, k + 1]

    x = _emit(phase, E, sigma, rng)                           # (N, W, d_in)

    return FreqBenchData(
        x=torch.from_numpy(x),
        y=torch.from_numpy(cls.astype(np.int64)),
        A_loc=1.0 / n_classes,
        A_oracle=1.0,
        n_classes=n_classes,
        bench=f"rs_D{degree}",
        velocities=torch.from_numpy(m_D),                     # signed leading
        coeffs=torch.from_numpy(m.astype(np.float32)),        # full message
    )


def rs_oracle_acc(data: FreqBenchData, *, M: int, degree: int) -> float:
    """Symbolic oracle accuracy: recover the leading class via the D-th
    finite difference of the (observed) phase mod M. Used only for sanity
    checks — confirms A_oracle = 1 at σ = 0. Reconstructs phase from x by
    nearest emission direction is overkill here; we re-derive from coeffs.
    """
    m = data.coeffs.numpy().astype(np.int64)                  # (N, D+1)
    omega = _leading_ladder(int(data.n_classes))
    # D-th difference of a degree-D Newton series is exactly m_D.
    pred_mD = m[:, degree] % M
    truth = omega[data.y.numpy()] % M
    return float((pred_mD == truth).mean())
