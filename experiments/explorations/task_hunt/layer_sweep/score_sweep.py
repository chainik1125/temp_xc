"""Frozen mechanical scorer for the layer sweep (CARD.md § 4 — staged
in the freeze commit, BEFORE any cell runs).

Reads `results/screen_{key}_hs{hs}.json` for every (model, hs) pair
in the RULED probe set plus the committed parent screens as the
anchor column (hunt3 for cnov, diafaces for tt, both at their frozen
screen layer), and emits `results/depth_profile.{json,md}`:

per (face, model) a depth table — rows = hs (with resid_post L),
columns = the card § 4 readout arms — plus the mechanical flags the
card pre-registers. HARD-FAILS on any missing cell (calib-card
precedent): a partial sweep is reported as FAILED, never silently
truncated.

Screens only: this scorer issues NO KEEP/KILL. It describes the
depth profile against the (layer-independent) label-side floors.

Run: .venv/bin/python -m experiments.explorations.task_hunt.layer_sweep.score_sweep
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
H3_RES = HERE.parent / "hunt3" / "results"
DIA_RES = HERE.parent / "diafaces" / "results"

# RULED probe set (default resid_post-L reading, LOG 6307ce5a3; if
# mac-local overrules to hs-index before probe-time, amend THIS dict in
# the amendment commit — the capture union covers both).
PROBE_SET = {
    "llama31_8b": [8, 15, 22, 29],
    "gemma2_2b": [7, 14, 21],
}
ANCHOR = {"llama31_8b": 14, "gemma2_2b": 14}   # parents' frozen screen hs
FACES = ("cnov", "tt")
PARENT_RES = {"cnov": H3_RES, "tt": DIA_RES}

# The readout arms per (face, hs) — canonical linear class scores,
# MLP reported beside (day2 ops rule: no max-over-arms; fixed arms).
# Metric matches the parents' summarize(): 3-class face cells carry
# ONLY acc_test; 2-class within-dialogue cells carry auc (verified
# against the committed screen JSONs before freeze).
READOUT = [
    ("tok_linear", "{f}/tok_linear", "acc_test"),
    ("tok_mlp", "{f}/tok_mlp", "acc_test"),
    ("position_floor", "{f}/position_floor", "acc_test"),
    ("vis_floor_T32", "{f}/T32/visible_evidence_floor", "acc_test"),
    ("actxmean_T32", "{f}/T32/actxmean_linear", "acc_test"),
    ("actxmean_foreign_T32", "{f}/T32/actxmean_foreign_linear", "acc_test"),
    ("win_T32", "{f}/T32/win_linear", "acc_test"),
    ("win_shuf_T32", "{f}/T32/win_shuf_linear", "acc_test"),
    ("null_win_T16", "{f}/T16/null_win_linear", "acc_test"),
    ("wd_tok", "{f}_wd/tok_linear", "auc"),
    ("wd_actxmean_T32", "{f}_wd/T32/actxmean_linear", "auc"),
    ("wd_win_T32", "{f}_wd/T32/win_linear", "auc"),
    ("wd_win_shuf_T32", "{f}_wd/T32/win_shuf_linear", "auc"),
]


def _metric(cell: dict, field: str) -> float:
    if field not in cell:
        raise KeyError(f"metric {field!r} absent; cell has {sorted(cell)}")
    return float(cell[field])


def load_cells(key: str, hs: int) -> dict:
    p = RES / f"screen_{key}_hs{hs}.json"
    if not p.exists():
        raise SystemExit(f"[score] MISSING {p} — sweep incomplete, "
                         "refusing to score a partial grid")
    return json.loads(p.read_text())["cells"], f"hs{hs}/"


def load_anchor(key: str, face: str) -> dict:
    p = PARENT_RES[face] / f"screen_{key}.json"
    if not p.exists():
        raise SystemExit(f"[score] MISSING parent anchor {p}")
    return json.loads(p.read_text())["cells"], ""


def main():
    profile: dict = {"probe_set": PROBE_SET, "anchor_hs": ANCHOR,
                     "faces": list(FACES), "tables": {}}
    md = ["# Layer-sweep depth profiles (auto-generated by "
          "score_sweep.py — frozen scorer, screens only, no KEEP/KILL)",
          ""]
    for face in FACES:
        for key in PROBE_SET:
            rows = []
            hs_list = list(PROBE_SET[key])
            for hs in hs_list:
                cells, prefix = load_cells(key, hs)
                row = {"hs": hs, "resid_L": hs - 1, "src": "sweep"}
                for name, patt, field in READOUT:
                    ck = prefix + patt.format(f=face)
                    if ck not in cells:
                        raise SystemExit(
                            f"[score] MISSING cell {ck} in {key} hs{hs} "
                            "— refusing partial scoring")
                    row[name] = round(_metric(cells[ck], field), 4)
                rows.append(row)
            # anchor column from the committed parent screen (context;
            # same instrument at its frozen layer, pre-sweep provenance)
            a_hs = ANCHOR[key]
            acells, _ = load_anchor(key, face)
            arow = {"hs": a_hs, "resid_L": a_hs - 1, "src": "parent"}
            for name, patt, field in READOUT:
                ck = patt.format(f=face)
                arow[name] = (round(_metric(acells[ck], field), 4)
                              if ck in acells else None)
            profile["tables"][f"{face}/{key}"] = {
                "sweep_rows": rows, "parent_anchor": arow}

            md += [f"## {face} — {key}", "",
                   "(3-class face arms = acc_test; wd arms = auc)", "",
                   "| hs | L | " + " | ".join(n for n, _, _ in READOUT)
                   + " | src |",
                   "|" + "---|" * (len(READOUT) + 3)]
            for r in rows + [arow]:
                md.append(
                    "| {} | {} | ".format(r["hs"], r["resid_L"])
                    + " | ".join(
                        ("—" if r.get(n) is None else f"{r[n]:.4f}")
                        for n, _, _ in READOUT)
                    + f" | {r['src']} |")
            # mechanical flags (card § 4 readings, described not verdicted)
            flags = []
            for r in rows:
                gap = r["actxmean_T32"] - r["vis_floor_T32"]
                flags.append(
                    f"hs{r['hs']}: actxmean−visfloor={gap:+.4f}; "
                    f"ord−shuf(win,T32)={r['win_T32'] - r['win_shuf_T32']:+.4f}; "
                    f"wd_actxmean={r['wd_actxmean_T32']:.4f}")
            md += ["", "flags: " + " · ".join(flags), ""]

    RES.mkdir(exist_ok=True)
    (RES / "depth_profile.json").write_text(json.dumps(profile, indent=1))
    (RES / "depth_profile.md").write_text("\n".join(md))
    print(f"[score] wrote {RES/'depth_profile.json'} + .md "
          f"({sum(len(t['sweep_rows']) for t in profile['tables'].values())}"
          " sweep rows)")


if __name__ == "__main__":
    main()
