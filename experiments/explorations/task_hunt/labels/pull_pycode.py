"""Python-code pull for the gen-4 CORPUS SCOUT (mac-c lane, beat
review ~12:15 item 3): code — a NON-natural-language, strongly
order-carried modality (definition→use structure) untouched by any
hunt substrate. New-corpus rules (pg19 precedent): exact re-pull
script, pinned revision, funnel counters, receipt.

    .venv/bin/python -m experiments.explorations.task_hunt.labels.pull_pycode

Source: ``codeparrot/codeparrot-clean-valid`` (permissively-licensed
GitHub Python, the deduplicated validation shard), revision PINNED
below. Per-file licence ships in the doc meta.

Recipe (label-FREE by design — no face statistic is consulted):

- stream ``train`` sequentially, first-N kept (the wikitext pull's
  convention; the valid split is itself a random shard of the
  deduplicated corpus, and a shuffle buffer stalls on this
  dataset's large row groups);
- keep files with ``autogenerated`` false, licence in the
  permissive allow-list (copyleft excluded — the corpus text ships
  in-repo), size in
  [MIN_CHARS, CAP_CHARS] (whole files only — code is never truncated,
  a cut file breaks ``tokenize``), and Python-3-parseable
  (``ast.parse``; the corpus is py2/py3 mixed — parse failures are
  counted, not shipped);
- stop at N_DOCS kept.

Funnel counters (scanned / autogen / size / no-parse / kept) and the
first-doc identity receipt go to ``pycode_corpus_receipt.json``;
corpus to ``pycode_corpus.json.gz``. Idempotent.
"""

from __future__ import annotations

import ast
import gzip
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "pycode_corpus.json.gz"
RECEIPT = HERE / "pycode_corpus_receipt.json"

DATASET = "codeparrot/codeparrot-clean-valid"
REVISION = "4db92d2ec0c1b4c41eeb439cfae16854511d9dcd"  # pinned
SPLIT = "train"
MIN_CHARS = 1_200
CAP_CHARS = 5_000
N_DOCS = 400
LICENSE_KEEP = {"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause",
                "cc0-1.0", "unlicense", "isc"}


def main():
    if OUT.exists():
        print(f"{OUT.name} exists — pull short-circuited (idempotent)")
        return
    import datasets as hfds

    ds = hfds.load_dataset(DATASET, split=SPLIT, streaming=True,
                           revision=REVISION)
    docs, n_seen, n_auto, n_size, n_noparse, n_lic = [], 0, 0, 0, 0, 0
    for row in ds:
        n_seen += 1
        if n_seen % 500 == 0:
            print(f"[pycode] scanned {n_seen}, kept {len(docs)}",
                  flush=True)
        if row.get("autogenerated"):
            n_auto += 1
            continue
        if str(row.get("license")).lower() not in LICENSE_KEEP:
            n_lic += 1
            continue
        src = row["content"]
        if not (MIN_CHARS <= len(src) <= CAP_CHARS):
            n_size += 1
            continue
        try:
            ast.parse(src)
        except (SyntaxError, ValueError, MemoryError, RecursionError):
            n_noparse += 1
            continue
        docs.append({"repo_name": row.get("repo_name"),
                     "path": row.get("path"),
                     "license": row.get("license"),
                     "content": src})
        if len(docs) % 100 == 0:
            print(f"[pycode] {len(docs)}/{N_DOCS} "
                  f"({n_seen} scanned)", flush=True)
        if len(docs) >= N_DOCS:
            break

    meta = {"dataset": DATASET, "revision": REVISION, "split": SPLIT,
            "order": "stream order, first-N kept (label-free; "
                     "shuffle stalls on this dataset's row groups)",
            "min_chars": MIN_CHARS, "cap_chars": CAP_CHARS,
            "whole_files_only": True, "n_docs": len(docs),
            "n_scanned": n_seen, "n_autogenerated": n_auto,
            "n_size_reject": n_size, "n_noparse_py3": n_noparse,
            "n_license_reject": n_lic,
            "license_keep": sorted(LICENSE_KEEP),
            "n_chars": sum(len(d["content"]) for d in docs),
            "licenses": sorted({str(d["license"]) for d in docs}),
            "label_free_pull": ("no face statistic consulted at pull "
                                "time — the corpus is not selected on "
                                "any label")}
    first = docs[0]
    meta["first_doc_receipt"] = {
        "repo_name": first["repo_name"], "path": first["path"],
        "sha256": hashlib.sha256(first["content"].encode()).hexdigest()}

    with gzip.open(OUT, "wt") as f:
        json.dump(docs, f)
    RECEIPT.write_text(json.dumps(meta, indent=1))
    print(json.dumps(meta, indent=1))


if __name__ == "__main__":
    main()
