"""Shared ELICITATION HARNESS — scaffold spec, exact event positions,
standard stream writer. Pure logic + I/O helpers; the model backend
lives in ``run_elicit.py`` so this file is testable on CPU with a stub
generator.

Authorized 2026-07-28 (LOG; briefing `safety-hunt-continuation.md`
re-opened). Design of record: `TIERC_PIPELINE_DESIGNS.md` § 3.

**Why this exists.** Every hunt kill this program has taken came from
corpus geometry we did not control: `dharm` 155.6 tok/document,
`warddebt`'s 154-token sentence kernel against T ≤ 32, `retryesc`'s
task-vocabulary leak (unigram 0.69–0.72). A generated corpus lets us
SET the geometry. The three lessons are wired in as first-class
scaffold parameters, not comments:

1. **Event spacing is chosen for the clock** — `gap_tokens` is
   specified per scaffold and the realised gap distribution is a
   receipt, so the claim zone per T is a design output, not a surprise.
2. **Vocabulary is controlled across event / non-event spans** — topic
   is drawn INDEPENDENTLY of the event schedule (`topic_of` never sees
   `events`), so token identity cannot predict event status the way it
   did in `retryesc`.
3. **No sentence-scale kernels** — faces are token-scale ages/rates
   over scaffold-inserted events; a sentence kernel spanning ~154
   tokens can never be computed inside T ≤ 64.

**What the harness does NOT do:** it does not make a candidate pass.
Event spacing and vocabulary control remove *confounds*; whether a
window beats a per-token probe on the resulting stream is left as a
genuine empirical question, and the per-token baseline is binding on
every corpus this produces.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

# ── turn sources ────────────────────────────────────────────────────
SRC_TEMPLATE = "template"     # fixed text from the scaffold (exact)
SRC_MODEL = "model"           # generated by the pinned model
SRC_SEED = "seed"             # drawn from a pinned seed file


@dataclass
class TurnSpec:
    role: str                  # "user" | "assistant"
    source: str                # SRC_*
    text: str | None = None    # for SRC_TEMPLATE
    is_event: bool = False     # scaffold-inserted event turn
    probe_eligible: bool = True
    max_new_tokens: int = 256
    meta: dict = field(default_factory=dict)


@dataclass
class DocPlan:
    """One document's ordered turn specs + the topic that generated it.
    ``topic`` is drawn INDEPENDENTLY of the event schedule."""
    turns: list[TurnSpec]
    topic: str
    doc_meta: dict = field(default_factory=dict)


def realised_gaps(event_first: np.ndarray, doc_off: np.ndarray) -> dict:
    """Receipt: inter-event token gaps, the clock the scaffold actually
    produced (vs the one it intended)."""
    gaps = []
    for d in range(len(doc_off) - 1):
        idx = np.flatnonzero(event_first[doc_off[d]:doc_off[d + 1]])
        if idx.size >= 2:
            gaps.extend(np.diff(idx).tolist())
    if not gaps:
        return {"n_gaps": 0}
    g = np.asarray(gaps, dtype=float)
    return {"n_gaps": int(g.size), "mean": float(g.mean()),
            "median": float(np.median(g)),
            "p10": float(np.percentile(g, 10)),
            "p90": float(np.percentile(g, 90)),
            "min": float(g.min()), "max": float(g.max())}


def claim_zone(raw_age: np.ndarray, elig: np.ndarray, Ts) -> dict:
    """Fraction of eligible rows whose event is INSIDE the window — the
    instrument that demoted `sycgen_rate` and read `retryesc`'s floors."""
    a = raw_age[elig & np.isfinite(raw_age)]
    if not a.size:
        return {"n_rows": 0}
    return {"n_rows": int(a.size), "mean": float(a.mean()),
            "median": float(np.median(a)),
            "frac_in_window": {f"T{T}": float((a <= T).mean()) for T in Ts}}


def vocabulary_control_check(token_ids: np.ndarray, event_first: np.ndarray,
                             doc_off: np.ndarray, topics: list[str],
                             window: int = 256) -> dict:
    """Did topic actually stay independent of event status?

    `retryesc` died because task vocabulary predicted the label. Here we
    can verify the control directly: the distribution of topics must not
    differ between documents with many vs few events. Reported as the
    per-topic event rate spread — a large spread means the control
    FAILED and the scaffold must be fixed before generation is trusted.
    """
    n_docs = len(doc_off) - 1
    per_doc_ev = np.array([int(event_first[doc_off[d]:doc_off[d + 1]].sum())
                           for d in range(n_docs)], dtype=float)
    per_doc_tok = np.diff(doc_off).astype(float)
    rate = per_doc_ev / np.maximum(per_doc_tok, 1)
    by_topic = {}
    for t in sorted(set(topics)):
        m = np.array([x == t for x in topics])
        if m.sum():
            by_topic[t] = float(rate[m].mean())
    vals = np.array(list(by_topic.values())) if by_topic else np.array([0.0])
    return {"per_topic_event_rate": by_topic,
            "spread_max_minus_min": float(vals.max() - vals.min()),
            "cv": float(vals.std() / max(vals.mean(), 1e-9)),
            "note": ("large spread => topic predicts event status => the "
                     "retryesc vocabulary leak is being rebuilt; fix the "
                     "scaffold, do not proceed")}


def write_stream(out_path: Path, *, token_ids, doc_off, event_first,
                 event_mask, probe_eligible, doc_split, extra=None) -> None:
    arrays = {"token_ids": np.asarray(token_ids, dtype=np.int32),
              "doc_off": np.asarray(doc_off, dtype=np.int64),
              "event_first": np.asarray(event_first, dtype=np.int8),
              "event_mask": np.asarray(event_mask, dtype=np.int8),
              "probe_eligible": np.asarray(probe_eligible, dtype=np.int8),
              "doc_split": np.asarray(doc_split, dtype=np.int8)}
    if extra:
        arrays.update(extra)
    np.savez_compressed(out_path, **arrays)


def corpus_receipt(*, scaffold_name: str, model_id: str, model_sha: str,
                   seed: int, temperature: float, top_p: float,
                   n_docs: int, n_tokens: int, gaps: dict,
                   vocab_check: dict, first_doc_text: str,
                   backend_note: str = "pod-hosted open weights (HF cache)",
                   extra=None) -> dict:
    """Full generation provenance — required in-card by the
    authorization. A generated corpus with no receipt is not evidence."""
    r = {"scaffold": scaffold_name,
         "generation": {"model_id": model_id, "model_sha": model_sha,
                        "seed": seed, "temperature": temperature,
                        "top_p": top_p,
                        "backend": backend_note},
         "n_docs": n_docs, "n_tokens": n_tokens,
         "realised_gaps": gaps,
         "vocabulary_control": vocab_check,
         "first_doc_sha256": hashlib.sha256(
             first_doc_text.encode()).hexdigest(),
         "model_generated_disclosure": (
             "corpus is MODEL-GENERATED; whether it enters a rebuttal "
             "exhibit or the appendix is the paper owner's call at quote "
             "time (authorization note, PTR)")}
    if extra:
        r.update(extra)
    return r


def save_receipt(path: Path, receipt: dict) -> None:
    path.write_text(json.dumps(receipt, indent=1))


# ── checkpointing (BLOCKING for every generation card, ruled 2026-07-28)
# My defect: run_elicit accumulated all documents in memory and wrote
# once at drain, so a run was ZERO-copy on disk until it finished and a
# late crash cost the whole spend. These helpers are the mechanism; any
# scaffold loop calls save_ckpt() every N turns and load_ckpt() at start.

CKPT_EVERY_TURNS = 5


def ckpt_path(out_dir: Path, tag: str) -> Path:
    return out_dir / f"elicit_{tag}_ckpt.json"


def save_ckpt(path: Path, docs: list, turn: int) -> None:
    """Atomic dump of partial transcripts. Written to a temp file and
    renamed so a crash mid-write cannot corrupt a good checkpoint."""
    payload = {"turn": int(turn),
               "docs": [{"plan": d["plan"],
                         "turns": [[r, t, bool(e)] for r, t, e in
                                   d["turns"]]} for d in docs]}
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(payload))
    tmp.replace(path)


def load_ckpt(path: Path):
    """Returns (docs, next_turn) or (None, 0) if no usable checkpoint."""
    if not path.exists():
        return None, 0
    try:
        payload = json.loads(path.read_text())
    except (ValueError, OSError):
        return None, 0
    docs = [{"plan": d["plan"],
             "turns": [(r, t, bool(e)) for r, t, e in d["turns"]]}
            for d in payload["docs"]]
    return docs, int(payload["turn"]) + 1
