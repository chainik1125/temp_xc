class Macros(dict):
    """dict subclass that returns "?" for missing keys instead of raising."""

    def __missing__(self, key):
        return "?"


def load_all() -> tuple[Macros, list[dict], list[dict], list[dict]]:
    macros = Macros(json.load(open(OUT / "paper_macros.json")))
    rows = json.load(open(OUT / "all_rows.json"))
    return macros, rows["headline"], rows["capability"], rows["mmlu"]


def short_arm(arm: str) -> str:
    return {"SAE (T=1)": "sae", "T-SAE (T=5)": "tsae", "TXC (T=5)": "txc",
            "—": "—"}.get(arm, arm)


def fmt_ci(lo, hi, fmt="{:+.2f}") -> str:
    return f"[{fmt.format(lo)}, {fmt.format(hi)}]"


def headline_table(headline: list[dict]) -> str:
    """Per-arm × per-dataset summary at K=20 across S3, S4, S5, S6 + DoM."""
    lines = ["| arm | dataset | method | K | ΔLR_harm | ΔLR_ben | leakage | "
             "Wilcoxon p (harm) |",
             "|-----|---------|--------|---|----------|---------|---------|"
             "-------------------|"]
    sort_key = lambda r: (
        {"sae": 0, "tsae": 1, "txc": 2}.get(short_arm(r["arm"]), 9),
        {"test_in": 0, "test_ood": 1, "test_mi": 2}.get(r["ds"], 9),
        {"S3_FSGA": 0, "S4_FSGA_clamp": 1, "S5_cFSGA": 2,
         "S6_FSGA_probecoef": 3}.get(r["method"], 9),
    )
    for r in sorted([r for r in headline
                     if r.get("K") in (20, None, "20") and r["ds"] in
                     ("test_in", "test_ood", "test_mi")], key=sort_key):
        leak_ci = fmt_ci(r["leakage_ci"][0], r["leakage_ci"][1])
        lines.append(
            f"| {r['arm']} | {r['ds']} | {r['method']} | {r.get('K') or '-'} | "
            f"{r['dh_mean']:+.3f} {fmt_ci(r['dh_ci'][0], r['dh_ci'][1], '{:+.2f}')} | "
            f"{r['db_mean']:+.3f} {fmt_ci(r['db_ci'][0], r['db_ci'][1], '{:+.2f}')} | "
            f"**{r['leakage_mean']:+.2f}** {leak_ci} | "
            f"{r['wilcoxon_p_h']:.1e} |")
    return "\n".join(lines)


def kcurve_table(headline: list[dict]) -> str:
    lines = ["| arm | K | ΔLR_harm (test_in) | leakage (test_in) | "
             "leakage (test_ood) | leakage (test_mi) |",
             "|-----|---|--------------------|-------------------|"
             "--------------------|-------------------|"]
    for arm in ("sae", "tsae", "txc"):
        for K in (1, 2, 5, 10, 20, 50, 100):
            row = {ds: None for ds in ("test_in", "test_ood", "test_mi")}
            dh_in = None
            for r in headline:
                if (r["method"] == "S3_FSGA" and short_arm(r["arm"]) == arm
                        and r.get("K") == K):
                    row[r["ds"]] = r
                    if r["ds"] == "test_in":
                        dh_in = r["dh_mean"]
            def cell(ds: str) -> str:
                r = row[ds]
                if r is None:
                    return "n/a"
                return f"{r['leakage_mean']:+.2f}"
            dh_str = f"{dh_in:+.3f}" if dh_in is not None else "n/a"
            lines.append(f"| {arm} | {K} | {dh_str} | {cell('test_in')} | "
                         f"{cell('test_ood')} | {cell('test_mi')} |")
    return "\n".join(lines)


def capability_table(cap: list[dict], mmlu: list[dict]) -> str:
    """KL on cap_alpaca + MMLU accuracy, per arm at K=20."""
    lines = ["| arm | method | K | KL on cap_alpaca (mean) | KL p95 | "
             "MMLU acc |",
             "|-----|--------|---|--------------------------|--------|"
             "----------|"]
    mmlu_by = {(r["method"], short_arm(r["arm"])): r for r in mmlu}
    base = next((r for r in mmlu if r["method"] == "baseline"), None)
    if base is not None:
        lines.append(f"| — | baseline | — | 0.000 | 0.000 | "
                     f"{base['acc']:.3f} |")
    for arm in ("sae", "tsae", "txc"):
        for r in cap:
            if (r["method"] == "S3_FSGA" and short_arm(r["arm"]) == arm
                    and r["K"] == 20):
                mm = mmlu_by.get(("S3_FSGA", arm))
                acc = f"{mm['acc']:.3f}" if mm else "n/a"
                lines.append(f"| {arm} | S3_FSGA | 20 | {r['kl_mean']:.4f} | "
                             f"{r['kl_p95']:.4f} | {acc} |")
        for m in ("S4_FSGA_clamp", "S5_cFSGA", "S6_FSGA_probecoef"):
            for r in cap:
                if (r["method"] == m and short_arm(r["arm"]) == arm):
                    lines.append(f"| {arm} | {m} | {r.get('K') or '-'} | "
                                 f"{r['kl_mean']:.4f} | {r['kl_p95']:.4f} | "
                                 f"n/a |")
    return "\n".join(lines)


